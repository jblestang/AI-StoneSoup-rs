#!/usr/bin/env python3
"""Regenerate lot4 tutorial fixture Rust modules from verification JSON."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAX_DETS = 16


def emit(json_name: str, out_name: str) -> None:
    data = json.loads((ROOT / "verification" / "fixtures" / json_name).read_text(encoding="utf-8"))
    n = int(data["num_steps"])
    lines = [
        f"// @generated by tools/python/lot4_fixtures_to_rust.py — do not edit",
        f"pub const NUM_STEPS: usize = {n};",
        f"pub const GATE: f64 = {data['gate']};",
        f"pub const DELETER_TRACE: f64 = {data['deleter_trace']};",
        f"pub const MIN_POINTS: u8 = {data['min_points']};",
        f"pub const PROCESS_NOISE: f64 = {data['process_noise']};",
        f"pub const MEAS_VAR: f64 = {data['meas_var']};",
    ]
    sec = int(data.get("timestep_seconds", 1))
    lines.append(f"pub const STEP_SECONDS: u32 = {sec};")

    offsets = data["meas_offsets"]
    flat = data["meas_xy"]
    if len(offsets) != n + 1:
        raise SystemExit(f"{json_name}: meas_offsets len {len(offsets)} != num_steps+1")
    dets_per = [offsets[i + 1] - offsets[i] for i in range(n)]
    if max(dets_per, default=0) > MAX_DETS:
        raise SystemExit(f"{json_name}: max dets {max(dets_per)} > {MAX_DETS}")

    lines.append(f"pub const MAX_DETS_PER_STEP: usize = {MAX_DETS};")
    lines.append(f"pub const MEAS_OFFSETS: [usize; NUM_STEPS + 1] = {offsets};")
    lines.append(f"pub const MEAS_XY: [[f64; 2]; {len(flat)}] = [")
    for row in flat:
        lines.append(f"    {row},")
    lines.append("];")

    snap_rows: list[list[float]] = []
    snap_counts: list[int] = []
    for snap in data["snapshots"]:
        means = snap["track_means"]
        snap_counts.append(len(means))
        snap_rows.extend(means)

    snap_offsets = [0]
    for c in snap_counts:
        snap_offsets.append(snap_offsets[-1] + c)

    lines.append(f"pub const SNAPSHOT_TRACK_COUNTS: [usize; NUM_STEPS] = {snap_counts};")
    lines.append(f"pub const SNAPSHOT_OFFSETS: [usize; NUM_STEPS + 1] = {snap_offsets};")
    lines.append(f"pub const SNAPSHOT_TRACK_MEANS: [[f64; 4]; {len(snap_rows)}] = [")
    for row in snap_rows:
        lines.append(f"    {row},")
    lines.append("];")

    out = ROOT / "crates" / "stonesoup-scenarios" / "src" / out_name
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


def main() -> None:
    emit("lot4_tutorial09.json", "lot4_tutorial09_fixtures.rs")
    emit("lot4_tutorial10.json", "lot4_tutorial10_fixtures.rs")


if __name__ == "__main__":
    main()

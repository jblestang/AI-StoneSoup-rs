#!/usr/bin/env python3
"""Export Lot 22 — bearings-only EKF example fixtures."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot22_bearing_only.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot22_bearing_only_fixtures.rs"


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot22_bearing_only.py — do not edit",
        f"pub const LOT22_NUM_STEPS: usize = {n};",
        "pub const LOT22_TRUTH: [[f64; 4]; LOT22_NUM_STEPS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT22_TRACK: [[f64; 4]; LOT22_NUM_STEPS] = [")
    for row in payload["track"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT22_PLATFORM_XY: [[f64; 2]; LOT22_NUM_STEPS] = [")
    for row in payload["platform_xy"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.dataassociator.neighbour import NearestNeighbour
    from stonesoup.deleter.time import UpdateTimeStepsDeleter
    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.initiator.simple import SinglePointInitiator
    from stonesoup.measures import Mahalanobis
    from stonesoup.models.measurement.nonlinear import Cartesian2DToBearing
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.platform.base import MovingPlatform
    from stonesoup.predictor.kalman import ExtendedKalmanPredictor
    from stonesoup.sensor.radar.radar import RadarBearing
    from stonesoup.simulator.platform import PlatformDetectionSimulator
    from stonesoup.simulator.simple import SingleTargetGroundTruthSimulator
    from stonesoup.tracker.simple import SingleTargetTracker
    from stonesoup.types.array import CovarianceMatrix, StateVector
    from stonesoup.types.state import GaussianState, State
    from stonesoup.updater.kalman import ExtendedKalmanUpdater

    np.random.seed(2001)
    start_time = datetime.now()

    platform_state_vector = StateVector([[0], [-5], [0], [-7]])
    platform_state = State(platform_state_vector, start_time)
    platform_transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.0), ConstantVelocity(0.0)]
    )
    platform = MovingPlatform(
        states=platform_state,
        position_mapping=(0, 2),
        velocity_mapping=(1, 3),
        transition_model=platform_transition_model,
    )

    noise_covar = CovarianceMatrix(np.diag([np.deg2rad(0.025) ** 2]))
    radar = RadarBearing(
        ndim_state=4,
        position_mapping=(0, 2),
        noise_covar=noise_covar,
    )
    platform.add_sensor(radar)

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(1.0), ConstantVelocity(1.0)]
    )
    initial_target_state = GaussianState(
        [50, 0, 50, 0],
        np.diag([1, 1, 1, 1]) ** 2,
        timestamp=start_time,
    )
    groundtruth_simulation = SingleTargetGroundTruthSimulator(
        transition_model=transition_model,
        initial_state=initial_target_state,
        timestep=timedelta(seconds=1),
        number_steps=100,
    )

    meas_model = Cartesian2DToBearing(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=noise_covar,
    )
    sim = PlatformDetectionSimulator(
        groundtruth=groundtruth_simulation, platforms=[platform]
    )

    predictor = ExtendedKalmanPredictor(transition_model)
    updater = ExtendedKalmanUpdater(measurement_model=None)
    initiator = SinglePointInitiator(
        prior_state=initial_target_state,
        measurement_model=meas_model,
    )
    hypothesiser = DistanceHypothesiser(
        predictor, updater, measure=Mahalanobis(), missed_distance=5
    )
    data_associator = NearestNeighbour(hypothesiser)
    deleter = UpdateTimeStepsDeleter(time_steps_since_update=3)
    kalman_tracker = SingleTargetTracker(
        initiator=initiator,
        deleter=deleter,
        detector=sim,
        data_associator=data_associator,
        updater=updater,
    )

    truth_rows = []
    track_rows = []
    platform_rows = []

    for _time, ctracks in kalman_tracker:
        truths = list(groundtruth_simulation.current[1])
        if not truths:
            continue
        truth_rows.append(state_mean(truths[0]))
        plat = platform.state
        platform_rows.append([float(plat.state_vector[0, 0]), float(plat.state_vector[2, 0])])
        if ctracks:
            track = next(iter(ctracks))
            track_rows.append(state_mean(track.states[-1]))
        else:
            track_rows.append(track_rows[-1] if track_rows else state_mean(initial_target_state))

    if len(truth_rows) != len(track_rows):
        raise SystemExit(
            f"truth/track length mismatch {len(truth_rows)} vs {len(track_rows)}"
        )

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_steps": len(truth_rows),
        "truth": truth_rows,
        "track": track_rows,
        "platform_xy": platform_rows,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Export Lot 25 — ParticleFlow.py (bootstrap PF vs Gromov flow vs parallel-EKF flow)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot25_particle_flow.json"
RUST = ROOT / "crates/stonesoup-scenarios/src/lot25_particle_flow_fixtures.rs"


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def particle_state_mean(state) -> list[float]:
    import numpy as np

    sv = state.state_vector
    if state.particles:
        w = np.array([float(p.weight) for p in state.particles], dtype=np.float64)
    else:
        w = np.ones(sv.shape[1], dtype=np.float64)
    w = w / w.sum()
    return [float((sv[i, :] * w).sum()) for i in range(sv.shape[0])]


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot25_particle_flow.py — do not edit",
        f"pub const LOT25_NUM_STEPS: usize = {n};",
        "pub const LOT25_TRUTH: [[f64; 4]; LOT25_NUM_STEPS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    for tag, key in (
        ("BOOTSTRAP", "bootstrap"),
        ("GROMOV_FLOW", "gromov_flow"),
        ("PARALLEL_EKF", "parallel_ekf"),
    ):
        lines.append(f"pub const LOT25_{tag}_TRACK: [[f64; 4]; LOT25_NUM_STEPS] = [")
        for row in payload[key]:
            lines.append(f"    {row},")
        lines.append("];")
    lines.append("pub const LOT25_MEAS_BR: [[f64; 2]; LOT25_NUM_STEPS] = [")
    for row in payload["meas_br"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from scipy.stats import multivariate_normal
    from stonesoup.models.measurement.nonlinear import CartesianToBearingRange
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.particle import ParticleFlowKalmanPredictor, ParticlePredictor
    from stonesoup.resampler.particle import SystematicResampler
    from stonesoup.types.detection import Detection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.numeric import Probability
    from stonesoup.types.particle import Particle
    from stonesoup.types.state import ParticleState
    from stonesoup.types.track import Track
    from stonesoup.updater.particle import (
        GromovFlowKalmanParticleUpdater,
        GromovFlowParticleUpdater,
        ParticleUpdater,
    )

    np.random.seed(2020)
    start_time = datetime(2020, 1, 1)
    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.05), ConstantVelocity(0.05)]
    )
    measurement_model = CartesianToBearingRange(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([np.radians(0.5), 1]),
    )

    truth = GroundTruthPath([GroundTruthState([0, 1, 0, 1], timestamp=start_time)])
    for k in range(1, 21):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1], noise=True, time_interval=timedelta(seconds=1)
                ),
                timestamp=start_time + timedelta(seconds=k),
            )
        )

    measurements = []
    truth_rows = []
    for state in truth:
        truth_rows.append(state_mean(state))
        vec = measurement_model.function(state, noise=True)
        measurements.append(
            Detection(vec, timestamp=state.timestamp, measurement_model=measurement_model)
        )

    number_particles = 1000
    samples = multivariate_normal.rvs(
        np.array([0, 1, 0, 1]), np.diag([1.5, 0.5, 1.5, 0.5]), size=number_particles
    )
    weight = Probability(1 / number_particles)
    particles = [Particle(sample.reshape(-1, 1), weight=weight) for sample in samples]

    predictors = [
        ParticlePredictor(transition_model),
        ParticlePredictor(transition_model),
        ParticleFlowKalmanPredictor(transition_model),
    ]
    p_updater = ParticleUpdater(measurement_model)
    p_updater.resampler = SystematicResampler()
    updaters = [
        p_updater,
        GromovFlowParticleUpdater(measurement_model),
        GromovFlowKalmanParticleUpdater(measurement_model),
    ]
    counts = [1000, 50, 50]
    keys = ["bootstrap", "gromov_flow", "parallel_ekf"]
    tracks_out = {k: [] for k in keys}

    for pred, upd, n, key in zip(predictors, updaters, counts, keys):
        track = Track()
        prior = ParticleState(None, particle_list=particles[:n], timestamp=start_time)
        for measurement in measurements:
            prediction = pred.predict(prior, timestamp=measurement.timestamp)
            hypothesis = SingleHypothesis(prediction, measurement)
            post = upd.update(hypothesis)
            track.append(post)
            tracks_out[key].append(particle_state_mean(post))
            prior = track[-1]

    payload = {
        "num_steps": len(truth_rows),
        "truth": truth_rows,
        "bootstrap": tracks_out["bootstrap"],
        "gromov_flow": tracks_out["gromov_flow"],
        "parallel_ekf": tracks_out["parallel_ekf"],
        "meas_br": [
            [float(m.state_vector[0, 0]), float(m.state_vector[1, 0])] for m in measurements
        ],
        "upstream_sha": UPSTREAM_SHA,
        "upstream_path": "docs/examples/filters/ParticleFlow.py",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    write_rust(payload)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT} sha256={digest}")
    print(f"wrote {RUST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

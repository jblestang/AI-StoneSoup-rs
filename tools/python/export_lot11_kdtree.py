#!/usr/bin/env python3
"""Export Lot 11 KD-tree GNN tutorial reference (scaled ``KDTree_Tutorial.py``)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot11_kdtree.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot11_kdtree_fixtures.rs"


def track_means(tracks) -> list[list[float]]:
    rows = []
    for t in tracks:
        s = t.states[-1]
        rows.append([float(s.state_vector[i, 0]) for i in range(4)])
    rows.sort(key=lambda r: (r[0], r[2]))
    return rows


def write_rust(payload: dict) -> None:
    lines = [
        "// @generated by tools/python/export_lot11_kdtree.py — do not edit",
        f"pub const LOT11_NUM_STEPS: usize = {payload['num_steps']};",
        f"pub const LOT11_GATE: f64 = {payload['gate']};",
        f"pub const LOT11_DELETER_TRACE: f64 = {payload['deleter_trace']};",
        f"pub const LOT11_MIN_POINTS: u8 = {payload['min_points']};",
        f"pub const LOT11_STEP_SECONDS: u32 = {payload['step_seconds']};",
        f"pub const LOT11_PROCESS_NOISE: f64 = {payload['process_noise']};",
        f"pub const LOT11_MEAS_VAR: f64 = {payload['meas_var']};",
        "pub const LOT11_MEAS_OFFSETS: [usize; LOT11_NUM_STEPS + 1] = [",
    ]
    for o in payload["meas_offsets"]:
        lines.append(f"    {o},")
    lines.append("];")
    lines.append("pub const LOT11_MEAS_XY: [[f64; 2]; LOT11_MEAS_OFFSETS[LOT11_NUM_STEPS]] = [")
    for row in payload["meas_xy"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT11_SNAPSHOT_OFFSETS: [usize; LOT11_NUM_STEPS + 1] = [")
    for o in payload["snapshot_offsets"]:
        lines.append(f"    {o},")
    lines.append("];")
    lines.append(
        "pub const LOT11_SNAPSHOT_TRACK_MEANS: [[f64; 4]; "
        "LOT11_SNAPSHOT_OFFSETS[LOT11_NUM_STEPS]] = ["
    )
    for row in payload["snapshot_means"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.dataassociator.tree import DetectionKDTreeGNN2D
    from stonesoup.deleter.error import CovarianceBasedDeleter
    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.initiator.simple import MultiMeasurementInitiator
    from stonesoup.measures import Mahalanobis
    from stonesoup.models.measurement.linear import LinearGaussian
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.simulator.simple import MultiTargetGroundTruthSimulator, SimpleDetectionSimulator
    from stonesoup.tracker.simple import MultiTargetTracker
    from stonesoup.types.array import CovarianceMatrix, StateVector
    from stonesoup.types.state import GaussianState
    from stonesoup.updater.kalman import KalmanUpdater

    np.random.seed(42)
    timestep_size = timedelta(seconds=5)
    number_of_steps = 12
    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.05), ConstantVelocity(0.05)]
    )
    initial_state = GaussianState(
        StateVector([[0], [0], [0], [0]]),
        CovarianceMatrix(np.diag([4, 0.5, 4, 0.5])),
    )
    groundtruth_sim = MultiTargetGroundTruthSimulator(
        transition_model=transition_model,
        initial_state=initial_state,
        timestep=timestep_size,
        number_steps=number_of_steps,
        birth_rate=0.15,
        death_probability=0.05,
        initial_number_targets=8,
    )
    measurement_model = LinearGaussian(4, [0, 2], np.diag([0.25, 0.25]))
    detection_sim = SimpleDetectionSimulator(
        groundtruth=groundtruth_sim,
        measurement_model=measurement_model,
        detection_probability=0.9,
        meas_range=np.array([[-1, 1], [-1, 1]]) * 500,
        clutter_rate=20,
    )

    predictor = KalmanPredictor(transition_model)
    updater = KalmanUpdater(measurement_model)
    hypothesiser = DistanceHypothesiser(
        predictor, updater, measure=Mahalanobis(), missed_distance=3
    )
    data_associator = DetectionKDTreeGNN2D(
        hypothesiser=hypothesiser,
        predictor=predictor,
        updater=updater,
        number_of_neighbours=3,
        max_distance_covariance_multiplier=3,
    )
    deleter = CovarianceBasedDeleter(covar_trace_thresh=100)
    initiator = MultiMeasurementInitiator(
        prior_state=GaussianState([[0], [0], [0], [0]], np.diag([0, 0.5, 0, 0.5])),
        measurement_model=measurement_model,
        deleter=deleter,
        data_associator=data_associator,
        updater=updater,
        min_points=3,
    )
    tracker = MultiTargetTracker(
        initiator=initiator,
        deleter=deleter,
        detector=detection_sim,
        data_associator=data_associator,
        updater=updater,
    )

    meas_xy: list[list[float]] = []
    meas_offsets = [0]
    snapshot_means: list[list[float]] = []
    snapshot_offsets = [0]

    for _time, tracks in tracker:
        step = len(meas_offsets) - 1
        dets = list(detection_sim.detections)
        for d in dets:
            meas_xy.append(
                [float(d.state_vector[0, 0]), float(d.state_vector[1, 0])]
            )
        meas_offsets.append(len(meas_xy))
        for row in track_means(tracks):
            snapshot_means.append(row)
        snapshot_offsets.append(len(snapshot_means))

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_steps": number_of_steps,
        "gate": 3.0,
        "deleter_trace": 100.0,
        "min_points": 3,
        "step_seconds": 5,
        "process_noise": 0.05,
        "meas_var": 0.25,
        "meas_offsets": meas_offsets,
        "meas_xy": meas_xy,
        "snapshot_offsets": snapshot_offsets,
        "snapshot_means": snapshot_means,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

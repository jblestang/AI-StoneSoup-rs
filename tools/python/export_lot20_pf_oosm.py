#!/usr/bin/env python3
"""Export Lot 20 — particle filter OOSM example fixtures."""
from __future__ import annotations

import hashlib
import json
from copy import deepcopy
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot20_pf_oosm.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot20_pf_oosm_fixtures.rs"


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def write_rust(payload: dict) -> None:
    n = payload["num_scans"]
    lines = [
        "// @generated by tools/python/export_lot20_pf_oosm.py — do not edit",
        f"pub const LOT20_NUM_SCANS: usize = {n};",
        f"pub const LOT20_NUM_PARTICLES: usize = {payload['num_particles']};",
        f"pub const LOT20_Q: f64 = {payload['q']};",
        f"pub const LOT20_PRIOR_MEAN: [f64; 4] = {payload['prior_mean']};",
        f"pub const LOT20_PRIOR_COV_DIAG: [f64; 4] = {payload['prior_cov_diag']};",
        "pub const LOT20_TRUTH: [[f64; 4]; LOT20_NUM_SCANS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT20_ARRIVAL_TRUTH_INDEX: [usize; LOT20_NUM_SCANS] = [")
    for i in payload["arrival_truth_index"]:
        lines.append(f"    {i},")
    lines.append("];")
    lines.append("pub const LOT20_OOSM_TRACK: [[f64; 4]; LOT20_NUM_SCANS] = [")
    for row in payload["oosm_track"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT20_IGNORE_TRACK: [[f64; 4]; LOT20_NUM_SCANS] = [")
    for row in payload["ignore_track"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from scipy.stats import multivariate_normal
    from stonesoup.models.measurement.nonlinear import CartesianToBearingRange
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.particle import ParticlePredictor
    from stonesoup.resampler.particle import ESSResampler
    from stonesoup.types.detection import TrueDetection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.numeric import Probability
    from stonesoup.types.particle import Particle
    from stonesoup.types.state import GaussianState, ParticleState, StateVector
    from stonesoup.types.track import Track
    from stonesoup.updater.particle import ParticleUpdater

    start_time = datetime.now().replace(microsecond=0)
    np.random.seed(1908)
    num_steps = 65
    number_particles = 256

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.05), ConstantVelocity(0.05)]
    )
    truth = GroundTruthPath(
        [GroundTruthState([0, 1, -100, 0.3], timestamp=start_time)]
    )
    timestamps = [start_time]
    truth_rows = [state_mean(truth[0])]
    for k in range(1, num_steps):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1],
                    noise=True,
                    time_interval=timedelta(seconds=5),
                ),
                timestamp=start_time + timedelta(seconds=5 * k),
            )
        )
        timestamps.append(truth[k].timestamp)
        truth_rows.append(state_mean(truth[k]))

    measurement_model = CartesianToBearingRange(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([np.radians(10), 50]),
        translation_offset=np.array([[500], [-500]]),
    )

    scans = []
    for k in range(num_steps):
        delay = 25 if k % 5 == 0 and k > 0 else 0
        measurement = measurement_model.function(truth[k], noise=True)
        detections = {
            TrueDetection(
                state_vector=measurement,
                groundtruth_path=truth,
                measurement_model=measurement_model,
                timestamp=truth[k].timestamp,
            )
        }
        scans.append((truth[k].timestamp + timedelta(seconds=delay), k, detections))

    arrival_time_ordered = sorted(scans, key=lambda dscan: dscan[0])
    arrival_truth_index = [row[1] for row in arrival_time_ordered]
    arrival_scans = [(row[0], row[2]) for row in arrival_time_ordered]

    predictor = ParticlePredictor(transition_model)
    resampler = ESSResampler()
    updater = ParticleUpdater(measurement_model=measurement_model, resampler=resampler)

    prior_state = GaussianState(
        StateVector([0, 1, -100, 0.3]),
        np.diag([10, 1, 10, 1]),
    )
    samples = multivariate_normal.rvs(
        np.array(prior_state.state_vector).reshape(-1),
        prior_state.covar,
        size=number_particles,
    )
    particles = [
        Particle(sample.reshape(-1, 1), weight=Probability(1.0)) for sample in samples
    ]
    particle_prior = ParticleState(
        state_vector=None, particle_list=particles, timestamp=timestamps[0]
    )

    track = Track(particle_prior)
    track2 = deepcopy(track)
    particle_prior2 = deepcopy(particle_prior)

    oosm_track = [state_mean(particle_prior)]
    ignore_track = [state_mean(particle_prior2)]

    for k in range(1, len(arrival_time_ordered)):
        scan = arrival_time_ordered[k][2]
        arrival_time = next(iter(scan)).timestamp

        if arrival_time > timestamps[k - 1]:
                for detection in scan:
                    prediction = predictor.predict(
                        particle_prior, timestamp=detection.timestamp
                    )
                    hypothesis = SingleHypothesis(prediction, detection)
                    post = updater.update(hypothesis)
                    track.append(post)
                    particle_prior = track[-1]

                for detection in scan:
                    prediction = predictor.predict(
                        particle_prior2, timestamp=detection.timestamp
                    )
                    hypothesis = SingleHypothesis(prediction, detection)
                    post = updater.update(hypothesis)
                    track2.append(post)
                    particle_prior2 = track2[-1]
        else:
            scan_time_arrival = [
                arrival_time_ordered[kk][0] for kk in range(0, k - 1)
            ]
            delta_time = [abs(entry - arrival_time) for entry in scan_time_arrival]
            tb_index = delta_time.index(min(delta_time))

            sample_state = [
                track[tb_index].state_vector[ii].mean()
                for ii in range(len(track[tb_index].state_vector))
            ]
            samples = multivariate_normal.rvs(
                np.array(sample_state).reshape(-1),
                np.diag([10, 1, 10, 1]),
                size=number_particles,
            )
            particles = [
                Particle(sample.reshape(-1, 1), weight=Probability(1.0))
                for sample in samples
            ]
            particle_prior = ParticleState(
                state_vector=None,
                particle_list=particles,
                timestamp=scan_time_arrival[tb_index],
            )

            for detection in scan:
                prediction = predictor.predict(
                    particle_prior, timestamp=detection.timestamp
                )
                hypothesis = SingleHypothesis(prediction, detection)
                post = updater.update(hypothesis)

            new_track = Track()
            for itrack in range(len(track)):
                if itrack == tb_index:
                    new_track.append(track[itrack])
                    new_track.append(post)
                else:
                    new_track.append(track[itrack])
            track = new_track
            particle_prior = resampler.resample(new_track[-1])

        oosm_track.append(state_mean(track[-1]))
        ignore_track.append(state_mean(track2[-1]))

    if len(oosm_track) != num_steps:
        raise SystemExit(
            f"expected {num_steps} oosm snapshots, got {len(oosm_track)}"
        )

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_scans": num_steps,
        "num_particles": number_particles,
        "q": 0.05,
        "prior_mean": [0.0, 1.0, -100.0, 0.3],
        "prior_cov_diag": [10.0, 1.0, 10.0, 1.0],
        "truth": truth_rows,
        "arrival_truth_index": arrival_truth_index,
        "oosm_track": oosm_track,
        "ignore_track": ignore_track,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Export Lot 13 Multi Sensor Management tutorial (``02_MultiSensorManagement.py``)."""
from __future__ import annotations

import hashlib
import json
import random
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot13_multi_sensor.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot13_multi_sensor_fixtures.rs"
N_SENSORS = 2


def track_means(tracks) -> list[list[float]]:
    rows = []
    for t in sorted(tracks, key=lambda tr: (tr.state_vector[0, 0], tr.state_vector[2, 0])):
        s = t.states[-1]
        rows.append([float(s.state_vector[i, 0]) for i in range(4)])
    return rows


def truth_snapshot(truths, timestep) -> list[list[float]]:
    rows = []
    for truth in sorted(truths, key=lambda t: t.id):
        for state in truth:
            if state.timestamp == timestep:
                rows.append([float(state.state_vector[i, 0]) for i in range(4)])
                break
    return rows


def sorted_sensors(sensor_set):
    return sorted(sensor_set, key=lambda s: float(s.position[1, 0]))


def sensor_index_map(sensor_set) -> dict:
    ordered = sorted_sensors(sensor_set)
    return {id(s): i for i, s in enumerate(ordered)}


def run_loop(sensor_set, tracks, truths, timesteps, manager):
    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.measures import Mahalanobis
    from stonesoup.dataassociator.neighbour import GNNWith2DAssignment
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.updater.kalman import ExtendedKalmanUpdater
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.005), ConstantVelocity(0.005)]
    )
    predictor = KalmanPredictor(transition_model)
    updater = ExtendedKalmanUpdater(measurement_model=None)
    hypothesiser = DistanceHypothesiser(
        predictor, updater, measure=Mahalanobis(), missed_distance=5
    )
    data_associator = GNNWith2DAssignment(hypothesiser)
    idx_map = sensor_index_map(sensor_set)

    steps = []
    for timestep in timesteps[1:]:
        chosen_actions = manager.choose_actions(tracks, timestep)
        for chosen_action in chosen_actions:
            for sensor, actions in chosen_action.items():
                sensor.add_actions(actions)
        dwell_rad = [0.0] * N_SENSORS
        detections = []
        measurements = []
        for sensor in sorted_sensors(sensor_set):
            sensor.act(timestep)
            si = idx_map[id(sensor)]
            dwell_rad[si] = float(sensor.dwell_centre[0, 0])
            for det in sensor.measure(
                {truth[timestep] for truth in truths}, noise=True
            ):
                detections.append(
                    [
                        float(det.state_vector[0, 0]),
                        float(det.state_vector[1, 0]),
                        float(si),
                    ]
                )
                measurements.append(det)
        hypotheses = data_associator.associate(tracks, measurements, timestep)
        for track in tracks:
            hypothesis = hypotheses[track]
            if hypothesis.measurement:
                post = updater.update(hypothesis)
                track.append(post)
            else:
                track.append(hypothesis.prediction)
        steps.append(
            {
                "dwell_rad": dwell_rad,
                "detections": detections,
                "track_means": track_means(tracks),
            }
        )
    return steps


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot13_multi_sensor.py — do not edit",
        f"pub const LOT13_NUM_STEPS: usize = {n};",
        f"pub const LOT13_NUM_TRUTHS: usize = {payload['num_truths']};",
        f"pub const LOT13_NUM_SENSORS: usize = {payload['num_sensors']};",
        f"pub const LOT13_MISSED_DISTANCE: f64 = {payload['missed_distance']};",
        f"pub const LOT13_SENSOR_Y: [f64; LOT13_NUM_SENSORS] = {payload['sensor_y']};",
        "pub const LOT13_PRIOR_MEANS: [[f64; 4]; LOT13_NUM_TRUTHS] = [",
    ]
    for row in payload["prior_means"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT13_TRUTH: [[[f64; 4]; LOT13_NUM_TRUTHS]; LOT13_NUM_STEPS] = [")
    for step in payload["truth"]:
        lines.append("    [")
        for row in step:
            lines.append(f"        {row},")
        lines.append("    ],")
    lines.append("];")

    for mode in ("brute", "random"):
        key = f"{mode}_steps"
        lines.append(
            f"pub const LOT13_{mode.upper()}_DWELL_RAD: "
            f"[[f64; LOT13_NUM_SENSORS]; LOT13_NUM_STEPS - 1] = ["
        )
        for s in payload[key]:
            lines.append(f"    {s['dwell_rad']},")
        lines.append("];")
        lines.append(
            f"pub const LOT13_{mode.upper()}_TRACK_OFFSETS: [usize; LOT13_NUM_STEPS] = ["
        )
        off = 0
        lines.append(f"    {off},")
        for s in payload[key]:
            off += len(s["track_means"])
            lines.append(f"    {off},")
        lines.append("];")
        lines.append(
            f"pub const LOT13_{mode.upper()}_TRACK_MEANS: [[f64; 4]; "
            f"LOT13_{mode.upper()}_TRACK_OFFSETS[LOT13_NUM_STEPS - 1]] = ["
        )
        for s in payload[key]:
            for row in s["track_means"]:
                lines.append(f"    {row},")
        lines.append("];")
        lines.append(
            f"pub const LOT13_{mode.upper()}_DET_OFFSETS: [usize; LOT13_NUM_STEPS] = ["
        )
        off = 0
        lines.append(f"    {off},")
        for s in payload[key]:
            off += len(s["detections"])
            lines.append(f"    {off},")
        lines.append("];")
        lines.append(
            f"pub const LOT13_{mode.upper()}_DETECTIONS: [[f64; 3]; "
            f"LOT13_{mode.upper()}_DET_OFFSETS[LOT13_NUM_STEPS - 1]] = ["
        )
        for s in payload[key]:
            for row in s["detections"]:
                lines.append(f"    {row},")
        lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from ordered_set import OrderedSet
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.state import GaussianState, StateVector
    from stonesoup.types.track import Track
    from stonesoup.types.angle import Angle
    from stonesoup.sensor.radar.radar import RadarRotatingBearingRange
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.updater.kalman import ExtendedKalmanUpdater
    from stonesoup.sensormanager import RandomSensorManager, BruteForceSensorManager
    from stonesoup.sensormanager.reward import UncertaintyRewardFunction

    np.random.seed(1990)
    random.seed(1990)

    start_time = datetime.now().replace(microsecond=0)
    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.005), ConstantVelocity(0.005)]
    )
    yps = range(0, 100, 10)
    ntruths = 3
    time_max = 20
    timesteps = [start_time + timedelta(seconds=k) for k in range(time_max)]

    truths = OrderedSet()
    xdirection = 1
    ydirection = 1
    for j in range(0, ntruths):
        truth = GroundTruthPath(
            [
                GroundTruthState(
                    [0, xdirection, yps[j], ydirection], timestamp=timesteps[0]
                )
            ],
            id=f"id{j}",
        )
        for k in range(1, time_max):
            truth.append(
                GroundTruthState(
                    transition_model.function(
                        truth[k - 1],
                        noise=True,
                        time_interval=timedelta(seconds=1),
                    ),
                    timestamp=timesteps[k],
                )
            )
        truths.add(truth)
        xdirection *= -1
        if j % 2 == 0:
            ydirection *= -1

    priors = []
    xdirection = 1.2
    ydirection = 1.2
    for j in range(0, ntruths):
        priors.append(
            GaussianState(
                [[0], [xdirection], [yps[j] + 0.1], [ydirection]],
                np.diag(np.array([0.5, 0.5, 0.5, 0.5]) + np.random.normal(0, 5e-4, 4)),
                timestamp=start_time,
            )
        )
        xdirection *= -1
        if j % 2 == 0:
            ydirection *= -1

    def make_sensor_set():
        sensor_set = set()
        for n in range(0, N_SENSORS):
            sensor = RadarRotatingBearingRange(
                position_mapping=(0, 2),
                noise_covar=np.array([[np.radians(0.5) ** 2, 0], [0, 1**2]]),
                ndim_state=4,
                position=np.array([[10], [n * 50]]),
                rpm=60,
                fov_angle=np.radians(30),
                dwell_centre=StateVector([0.0]),
                max_range=np.inf,
                resolution=Angle(np.radians(30)),
            )
            sensor.timestamp = start_time
            sensor_set.add(sensor)
        return sensor_set

    predictor = KalmanPredictor(transition_model)
    updater = ExtendedKalmanUpdater(measurement_model=None)
    reward_function = UncertaintyRewardFunction(predictor, updater)

    sensor_a = make_sensor_set()
    tracks_a = {Track([prior]) for prior in priors}
    random_mgr = RandomSensorManager(sensor_a)
    random_steps = run_loop(sensor_a, tracks_a, truths, timesteps, random_mgr)

    sensor_b = make_sensor_set()
    tracks_b = {Track([prior]) for prior in priors}
    brute_mgr = BruteForceSensorManager(sensor_b, reward_function=reward_function)
    brute_steps = run_loop(sensor_b, tracks_b, truths, timesteps, brute_mgr)

    truth_rows = [truth_snapshot(truths, ts) for ts in timesteps]
    sensor_y = [float(n * 50) for n in range(N_SENSORS)]

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_steps": time_max,
        "num_truths": ntruths,
        "num_sensors": N_SENSORS,
        "missed_distance": 5.0,
        "sensor_y": sensor_y,
        "prior_means": track_means({Track([p]) for p in priors}),
        "truth": truth_rows,
        "random_steps": random_steps,
        "brute_steps": brute_steps,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

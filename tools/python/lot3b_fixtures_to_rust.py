#!/usr/bin/env python3
"""Generate lot3b fixture Rust modules from verification JSON."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAX_DETS = 20


def write_meas_sets(lines: list, data: dict) -> None:
    flat_xy = []
    flat_true = []
    counts = []
    for step in data["measurement_sets"]:
        ms = step["measurements"]
        if len(ms) > MAX_DETS:
            raise SystemExit(f"too many dets: {len(ms)}")
        counts.append(len(ms))
        for m in ms:
            flat_xy.append(m["xy"])
            flat_true.append(1 if m["kind"] == "true" else 0)
    lines.append(f"pub const MAX_DETS_PER_STEP: usize = {MAX_DETS};")
    offsets = [0]
    for c in counts:
        offsets.append(offsets[-1] + c)
    lines.append(f"pub const MEAS_OFFSETS: [usize; NUM_STEPS + 1] = {offsets};")
    lines.append(f"pub const MEAS_XY: [[f64; 2]; {len(flat_xy)}] = [")
    for row in flat_xy:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append(f"pub const _MEAS_IS_TRUE: [u8; {len(flat_true)}] = {flat_true};")


def multitarget(out_name: str, json_name: str) -> None:
    data = json.loads((ROOT / "verification/fixtures" / json_name).read_text())
    n = data["num_steps"]
    lines = [
        "// @generated by tools/python/lot3b_fixtures_to_rust.py — do not edit",
        f"pub const NUM_STEPS: usize = {n};",
    ]
    for label in ("truth_a", "truth_b", "track_a", "track_b"):
        lines.append(f"pub const {label.upper()}: [[f64; 4]; NUM_STEPS + 1] = [")
        rows = data[label]
        if label.startswith("truth"):
            for row in rows:
                lines.append(f"    {row},")
        else:
            # tracks shorter by one if truth has 21 states — pad track at step 0 with prior
            if len(rows) == n:
                pass
            for row in rows:
                lines.append(f"    {row},")
        lines.append("];")
    # Fix truth to 21 rows, tracks to NUM_STEPS (20) only
    lines = [
        "// @generated by tools/python/lot3b_fixtures_to_rust.py — do not edit",
        f"pub const NUM_STEPS: usize = {n};",
        f"pub const TRUTH_A: [[f64; 4]; {len(data['truth_a'])}] = [",
    ]
    for row in data["truth_a"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append(f"pub const TRUTH_B: [[f64; 4]; {len(data['truth_b'])}] = [")
    for row in data["truth_b"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append(f"pub const TRACK_A_REF: [[f64; 4]; NUM_STEPS] = [")
    for row in data["track_a"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append(f"pub const TRACK_B_REF: [[f64; 4]; NUM_STEPS] = [")
    for row in data["track_b"]:
        lines.append(f"    {row},")
    lines.append("];")
    write_meas_sets(lines, data)
    out = ROOT / "crates/stonesoup-scenarios/src" / out_name
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


def single_track(out_name: str, json_name: str, track_key: str = "track") -> None:
    data = json.loads((ROOT / "verification/fixtures" / json_name).read_text())
    n = data["num_steps"]
    lines = [
        "// @generated by tools/python/lot3b_fixtures_to_rust.py — do not edit",
        f"pub const NUM_STEPS: usize = {n};",
        f"pub const TRUTH: [[f64; 4]; {len(data['truth'])}] = [",
    ]
    for row in data["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append(f"pub const TRACK_REF: [[f64; 4]; NUM_STEPS] = [")
    for row in data[track_key]:
        lines.append(f"    {row},")
    lines.append("];")
    write_meas_sets(lines, data)
    out = ROOT / "crates/stonesoup-scenarios/src" / out_name
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


def main() -> None:
    multitarget("lot3_multitarget_fixtures.rs", "lot3_multitarget.json")
    single_track("lot3_pda_fixtures.rs", "lot3_pda.json")
    multitarget("lot3_jpda_fixtures.rs", "lot3_jpda.json")


if __name__ == "__main__":
    main()

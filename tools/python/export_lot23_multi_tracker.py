#!/usr/bin/env python3
"""Export Lot 23 — Multi_Tracker_Example (EKF / UKF / PF / ESIF on manoeuvring targets)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from itertools import tee
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot23_multi_tracker.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot23_multi_tracker_fixtures.rs"

SENSOR_XY = (20.0, 0.0)


def sorted_track_means(tracks) -> list[list[float]]:
    rows = []
    for t in sorted(tracks, key=lambda tr: (tr.state_vector[0, 0], tr.state_vector[2, 0])):
        s = t.states[-1]
        rows.append([float(s.state_vector[i, 0]) for i in range(4)])
    return rows


def truth_at_time(ground_truth, time) -> list[list[float]]:
    rows = []
    for path in sorted(ground_truth, key=lambda p: p.id):
        for state in path:
            if state.timestamp == time:
                rows.append([float(state.state_vector[i, 0]) for i in range(4)])
                break
    return rows


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    nt = payload["num_truths"]
    lines = [
        "// @generated by tools/python/export_lot23_multi_tracker.py — do not edit",
        f"pub const LOT23_NUM_STEPS: usize = {n};",
        f"pub const LOT23_NUM_TRUTHS: usize = {nt};",
        f"pub const LOT23_SENSOR_X: f64 = {payload['sensor_x']};",
        f"pub const LOT23_SENSOR_Y: f64 = {payload['sensor_y']};",
        "pub const LOT23_TRUTH: [[[f64; 4]; LOT23_NUM_TRUTHS]; LOT23_NUM_STEPS] = [",
    ]
    for step in payload["truth"]:
        lines.append("    [")
        for row in step:
            lines.append(f"        {row},")
        lines.append("    ],")
    lines.append("];")
    lines.append("pub const LOT23_DET_OFFSETS: [usize; LOT23_NUM_STEPS + 1] = [")
    for v in payload["det_offsets"]:
        lines.append(f"    {v},")
    lines.append("];")
    lines.append("pub const LOT23_DETECTIONS: [[f64; 2]; LOT23_DET_OFFSETS[LOT23_NUM_STEPS]] = [")
    for row in payload["detections"]:
        lines.append(f"    {row},")
    lines.append("];")
    for tag, key in (
        ("EKF", "ekf"),
        ("UKF", "ukf"),
        ("PF", "pf"),
        ("ESIF", "esif"),
    ):
        lines.append(f"pub const LOT23_{tag}_TRACK_OFFSETS: [usize; LOT23_NUM_STEPS + 1] = [")
        for v in payload[f"{key}_track_offsets"]:
            lines.append(f"    {v},")
        lines.append("];")
        lines.append(
            f"pub const LOT23_{tag}_TRACK_MEANS: [[f64; 4]; "
            f"LOT23_{tag}_TRACK_OFFSETS[LOT23_NUM_STEPS]] = ["
        )
        for row in payload[f"{key}_track_means"]:
            lines.append(f"    {row},")
        lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def run_tracker(tracker, num_steps: int) -> tuple[list[list[list[float]]], list[int], list[list[float]]]:
    """Returns per-step sorted track means, cumulative offsets, flat track means."""
    per_step: list[list[list[float]]] = []
    flat: list[list[float]] = []
    offsets = [0]
    for step, (_time, current_tracks) in enumerate(tracker, 1):
        means = sorted_track_means(current_tracks)
        per_step.append(means)
        flat.extend(means)
        offsets.append(len(flat))
        if step >= num_steps:
            break
    return per_step, offsets, flat


def main() -> int:
    import numpy as np
    from stonesoup.dataassociator.neighbour import GNNWith2DAssignment
    from stonesoup.deleter.time import UpdateTimeDeleter
    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.initiator.simple import (
        GaussianParticleInitiator,
        MultiMeasurementInitiator,
        SimpleMeasurementInitiator,
    )
    from stonesoup.measures import Mahalanobis
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
        KnownTurnRate,
    )
    from stonesoup.platform import FixedPlatform
    from stonesoup.predictor.kalman import ExtendedKalmanPredictor, UnscentedKalmanPredictor
    from stonesoup.predictor.particle import ParticlePredictor
    from stonesoup.resampler.particle import ESSResampler
    from stonesoup.sensor.radar import RadarBearingRange
    from stonesoup.simulator.platform import PlatformDetectionSimulator
    from stonesoup.simulator.simple import SwitchMultiTargetGroundTruthSimulator
    from stonesoup.tracker.simple import MultiTargetTracker
    from stonesoup.types.array import CovarianceMatrix, StateVector
    from stonesoup.types.state import GaussianState, State
    from stonesoup.updater.kalman import ExtendedKalmanUpdater, UnscentedKalmanUpdater
    from stonesoup.updater.particle import ParticleUpdater
    from stonesoup.updater.slidinginnovation import ExtendedSlidingInnovationUpdater

    np.random.seed(2)
    start_time = datetime.now()
    number_steps = 20
    timestep_size = timedelta(seconds=1)

    initial_state = GaussianState(
        StateVector([[0], [0], [0], [0]]),
        CovarianceMatrix(np.diag([4, 0.5, 4, 0.5])),
    )
    constant_velocity = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.05), ConstantVelocity(0.05)]
    )
    turn_left = KnownTurnRate([0.05, 0.05], np.radians(20))
    turn_right = KnownTurnRate([0.05, 0.05], np.radians(-20))
    model_probs = np.array([[0.7, 0.15, 0.15], [0.4, 0.6, 0.0], [0.4, 0.0, 0.6]])

    n_truths = 3
    preexisting_states = []
    for _ in range(n_truths):
        x = np.random.randint(0, 40) - 1
        y = np.random.randint(0, 40) - 1
        y_vel = np.random.randint(-20, 20) / 10
        x_vel = np.random.randint(-20, 20) / 10
        preexisting_states.append(StateVector([x, x_vel, y, y_vel]))

    ground_truth_gen = SwitchMultiTargetGroundTruthSimulator(
        initial_state=initial_state,
        transition_models=[constant_velocity, turn_left, turn_right],
        model_probs=model_probs,
        number_steps=number_steps,
        timestep=timestep_size,
        birth_rate=0,
        death_probability=0,
        preexisting_states=preexisting_states,
    )

    sensor = RadarBearingRange(
        ndim_state=4,
        position_mapping=[0, 2],
        noise_covar=np.diag([np.radians(0.2), 0.2]),
        clutter_model=None,
    )
    platform = FixedPlatform(
        State(StateVector([20, 0, 0, 0])),
        position_mapping=[0, 2],
        sensors=[sensor],
    )

    detector = PlatformDetectionSimulator(ground_truth_gen, platforms=[platform])
    detector, det_ekf, det_ukf, det_esif, det_pf = tee(detector, 5)

    truth_steps: list[list[list[float]]] = []
    det_flat: list[list[float]] = []
    det_offsets = [0]
    ground_truth = set()

    for time, dets in detector:
        ground_truth |= ground_truth_gen.groundtruth_paths
        truth_steps.append(truth_at_time(ground_truth, time))
        for d in dets:
            det_flat.append([float(d.state_vector[0, 0]), float(d.state_vector[1, 0])])
        det_offsets.append(len(det_flat))

    transition_model_estimate = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.5), ConstantVelocity(0.5)]
    )
    predictor_ekf = ExtendedKalmanPredictor(transition_model_estimate)
    predictor_ukf = UnscentedKalmanPredictor(transition_model_estimate)
    predictor_pf = ParticlePredictor(transition_model_estimate)
    resampler = ESSResampler()
    updater_ekf = ExtendedKalmanUpdater(sensor)
    updater_ukf = UnscentedKalmanUpdater(sensor)
    updater_esif = ExtendedSlidingInnovationUpdater(
        measurement_model=None, layer_width=10 * np.diag(sensor.noise_covar)
    )
    updater_pf = ParticleUpdater(measurement_model=None, resampler=resampler)

    deleter = UpdateTimeDeleter(timedelta(seconds=5), delete_last_pred=True)
    init_transition = CombinedLinearGaussianTransitionModel(
        (ConstantVelocity(1), ConstantVelocity(1))
    )
    init_predictor_ekf = ExtendedKalmanPredictor(init_transition)
    init_predictor_ukf = UnscentedKalmanPredictor(init_transition)
    prior = GaussianState(np.array([[20], [0], [10], [0]]), np.diag([1, 1, 1, 1]))

    def make_initiator(predictor, updater):
        return MultiMeasurementInitiator(
            prior,
            measurement_model=None,
            deleter=deleter,
            data_associator=GNNWith2DAssignment(
                DistanceHypothesiser(
                    predictor, updater, Mahalanobis(), missed_distance=5
                )
            ),
            updater=updater,
            min_points=2,
        )

    initiator_ekf = make_initiator(init_predictor_ekf, updater_ekf)
    initiator_ukf = make_initiator(init_predictor_ukf, updater_ukf)
    initiator_esif = make_initiator(init_predictor_ekf, updater_esif)

    prior_pf = GaussianState(StateVector([20, 0, 10, 0]), np.diag([1, 1, 1, 1]) ** 2)
    initiator_part = SimpleMeasurementInitiator(
        prior_pf, measurement_model=None, skip_non_reversible=True
    )
    initiator_pf = GaussianParticleInitiator(
        number_particles=2000, initiator=initiator_part, use_fixed_covar=False
    )

    def assoc(updater, predictor):
        return GNNWith2DAssignment(
            DistanceHypothesiser(predictor, updater, Mahalanobis(), missed_distance=4)
        )

    trackers = {
        "ekf": MultiTargetTracker(
            initiator=initiator_ekf,
            deleter=deleter,
            detector=det_ekf,
            data_associator=assoc(updater_ekf, predictor_ekf),
            updater=updater_ekf,
        ),
        "ukf": MultiTargetTracker(
            initiator=initiator_ukf,
            deleter=deleter,
            detector=det_ukf,
            data_associator=assoc(updater_ukf, predictor_ukf),
            updater=updater_ukf,
        ),
        "esif": MultiTargetTracker(
            initiator=initiator_esif,
            deleter=deleter,
            detector=det_esif,
            data_associator=assoc(updater_esif, predictor_ekf),
            updater=updater_esif,
        ),
        "pf": MultiTargetTracker(
            initiator=initiator_pf,
            deleter=deleter,
            detector=det_pf,
            data_associator=assoc(updater_pf, predictor_pf),
            updater=updater_pf,
        ),
    }

    filter_exports = {}
    for key, tracker in trackers.items():
        _per, offsets, flat = run_tracker(tracker, number_steps)
        filter_exports[key] = (offsets, flat)

    payload = {
        "num_steps": number_steps,
        "num_truths": n_truths,
        "sensor_x": SENSOR_XY[0],
        "sensor_y": SENSOR_XY[1],
        "truth": truth_steps,
        "det_offsets": det_offsets,
        "detections": det_flat,
        "ekf_track_offsets": filter_exports["ekf"][0],
        "ekf_track_means": filter_exports["ekf"][1],
        "ukf_track_offsets": filter_exports["ukf"][0],
        "ukf_track_means": filter_exports["ukf"][1],
        "pf_track_offsets": filter_exports["pf"][0],
        "pf_track_means": filter_exports["pf"][1],
        "esif_track_offsets": filter_exports["esif"][0],
        "esif_track_means": filter_exports["esif"][1],
        "upstream_sha": UPSTREAM_SHA,
        "upstream_path": "docs/examples/filters/Multi_Tracker_Example.py",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    write_rust(payload)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT} sha256={digest}")
    print(f"wrote {RUST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

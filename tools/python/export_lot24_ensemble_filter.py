#!/usr/bin/env python3
"""Export Lot 24 — EnsembleFilterExample fixtures."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot24_ensemble_filter.json"
RUST = ROOT / "crates/stonesoup-scenarios/src/lot24_ensemble_filter_fixtures.rs"


def ensemble_mean(state) -> list[float]:
    sv = state.state_vector
    return [float(sv[i, :].mean()) for i in range(sv.shape[0])]


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot24_ensemble_filter.py — do not edit",
        f"pub const LOT24_NUM_STEPS: usize = {n};",
        f"pub const LOT24_SENSOR_X: f64 = {payload['sensor_x']};",
        f"pub const LOT24_SENSOR_Y: f64 = {payload['sensor_y']};",
        "pub const LOT24_TRUTH: [[f64; 4]; LOT24_NUM_STEPS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT24_TRACK: [[f64; 4]; LOT24_NUM_STEPS] = [")
    for row in payload["track"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT24_MEAS_BR: [[f64; 2]; LOT24_NUM_STEPS] = [")
    for row in payload["meas_br"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.models.measurement.nonlinear import CartesianToBearingRange
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.ensemble import EnsemblePredictor
    from stonesoup.types.detection import Detection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.state import EnsembleState
    from stonesoup.types.track import Track
    from stonesoup.updater.ensemble import EnsembleUpdater

    start_time = datetime.now()
    np.random.seed(1991)
    sensor_x = 50.0
    sensor_y = 0.0

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.05), ConstantVelocity(0.05)]
    )
    truth = GroundTruthPath([GroundTruthState([0, 1, 0, 1], timestamp=start_time)])
    for k in range(1, 21):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1], noise=True, time_interval=timedelta(seconds=1)
                ),
                timestamp=start_time + timedelta(seconds=k),
            )
        )

    measurement_model = CartesianToBearingRange(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([np.radians(0.2), 1]),
        translation_offset=np.array([[sensor_x], [sensor_y]]),
    )

    measurements = []
    truth_rows = []
    for state in truth:
        truth_rows.append(state_mean(state))
        measurement = measurement_model.function(state, noise=True)
        measurements.append(
            Detection(measurement, timestamp=state.timestamp, measurement_model=measurement_model)
        )

    predictor = EnsemblePredictor(transition_model)
    updater = EnsembleUpdater(measurement_model)
    ensemble = EnsembleState.generate_ensemble(
        mean=np.array([[0], [1], [0], [1]]),
        covar=np.diag([1.5, 0.5, 1.5, 0.5]),
        num_vectors=100,
    )
    prior = EnsembleState(state_vector=ensemble, timestamp=start_time)

    track_rows = []
    track = Track()
    for measurement in measurements:
        prediction = predictor.predict(prior, timestamp=measurement.timestamp)
        hypothesis = SingleHypothesis(prediction, measurement)
        post = updater.update(hypothesis)
        track.append(post)
        track_rows.append(ensemble_mean(post))
        prior = track[-1]

    n = len(truth_rows)
    payload = {
        "num_steps": n,
        "sensor_x": sensor_x,
        "sensor_y": sensor_y,
        "truth": truth_rows,
        "track": track_rows,
        "meas_br": [
            [float(m.state_vector[0, 0]), float(m.state_vector[1, 0])] for m in measurements
        ],
        "upstream_sha": UPSTREAM_SHA,
        "upstream_path": "docs/examples/filters/EnsembleFilterExample.py",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    write_rust(payload)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT} sha256={digest}")
    print(f"wrote {RUST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

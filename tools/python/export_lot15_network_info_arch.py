#!/usr/bin/env python3
"""Export Lot 15 — Information vs Network Architectures tutorial fixtures."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot15_network_info_arch.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot15_network_info_arch_fixtures.rs"

EXPORT_MODES = ("network", "information", "network_rm", "information_rm")


def track_means(tracks) -> list[list[float]]:
    rows = []
    for t in sorted(tracks, key=lambda tr: (tr.state_vector[0, 0], tr.state_vector[2, 0])):
        s = t.states[-1]
        rows.append([float(s.state_vector[i, 0]) for i in range(4)])
    return rows


def truth_snapshot(truths, timestep) -> list[list[float]]:
    rows = []
    for truth in sorted(truths, key=lambda t: t.id):
        for state in truth:
            if state.timestamp == timestep:
                rows.append([float(state.state_vector[i, 0]) for i in range(4)])
                break
    return rows


def reduce_tracks(tracks):
    from stonesoup.types.track import Track

    return {
        Track([s for s in track.last_timestamp_generator()])
        for track in tracks
    }


def run_arch_sim(arch, truths, timesteps):
    steps = []
    for time in timesteps:
        arch.measure(truths, noise=True)
        arch.propagate(time_increment=1)
        top = arch.top_level_nodes.pop()
        steps.append({"track_means": track_means(reduce_tracks(top.tracks))})
        arch.top_level_nodes.add(top)
    return steps


def run_arch_sim_f1(arch, truths, timesteps):
    steps = []
    for time in timesteps:
        arch.measure(truths, noise=True)
        arch.propagate(time_increment=1)
        top = [node for node in arch.all_nodes if node.label == "f1"][0]
        steps.append({"track_means": track_means(reduce_tracks(top.tracks))})
    return steps


def siap_averages(top_node, truths):
    from stonesoup.metricgenerator.tracktotruthmetrics import SIAPMetrics
    from stonesoup.measures import Euclidean
    from stonesoup.dataassociator.tracktotrack import TrackToTruth
    from stonesoup.metricgenerator.manager import MultiManager

    siap = SIAPMetrics(
        position_measure=Euclidean((0, 2)),
        velocity_measure=Euclidean((1, 3)),
        generator_name="siap",
        tracks_key="tracks",
        truths_key="truths",
    )
    associator = TrackToTruth(association_threshold=30)
    manager = MultiManager([siap], associator)
    manager.add_data({"tracks": top_node.tracks, "truths": truths}, overwrite=False)
    metrics = manager.generate_metrics()["siap"]
    out = {}
    for k in metrics:
        if k.startswith("SIAP") and not k.endswith(" at times"):
            m = metrics.get(k)
            out[k] = float(m.value)
    return out


def rust_mode_tag(mode: str) -> str:
    return {
        "network": "NETWORK",
        "information": "INFORMATION",
        "network_rm": "NETWORK_RM",
        "information_rm": "INFORMATION_RM",
    }[mode]


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot15_network_info_arch.py — do not edit",
        f"pub const LOT15_NUM_STEPS: usize = {n};",
        f"pub const LOT15_NUM_TRUTHS: usize = {payload['num_truths']};",
        "pub const LOT15_TRUTH: [[[f64; 4]; LOT15_NUM_TRUTHS]; LOT15_NUM_STEPS] = [",
    ]
    for step in payload["truth"]:
        lines.append("    [")
        for row in step:
            lines.append(f"        {row},")
        lines.append("    ],")
    lines.append("];")

    for mode in EXPORT_MODES:
        tag = rust_mode_tag(mode)
        key = f"{mode}_steps"
        lines.append(f"pub const LOT15_{tag}_TRACK_OFFSETS: [usize; LOT15_NUM_STEPS + 1] = [")
        off = 0
        lines.append(f"    {off},")
        for s in payload[key]:
            off += len(s["track_means"])
            lines.append(f"    {off},")
        lines.append("];")
        lines.append(
            f"pub const LOT15_{tag}_TRACK_MEANS: [[f64; 4]; "
            f"LOT15_{tag}_TRACK_OFFSETS[LOT15_NUM_STEPS]] = ["
        )
        for s in payload[key]:
            for row in s["track_means"]:
                lines.append(f"    {row},")
        lines.append("];")
        siap = payload[f"{mode}_siap"]
        keys = sorted(siap.keys())
        lines.append(f"pub const LOT15_{tag}_SIAP_KEYS: [&str; {len(keys)}] = [")
        for k in keys:
            lines.append(f'    "{k}",')
        lines.append("];")
        lines.append(f"pub const LOT15_{tag}_SIAP_VALUES: [f64; {len(keys)}] = [")
        for k in keys:
            lines.append(f"    {siap[k]},")
        lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    import random
    from ordered_set import OrderedSet
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.state import GaussianState, StateVector
    from stonesoup.types.angle import Angle
    from stonesoup.sensor.radar.radar import RadarRotatingBearingRange
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.updater.kalman import ExtendedKalmanUpdater
    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.measures import Mahalanobis
    from stonesoup.dataassociator.neighbour import GNNWith2DAssignment
    from stonesoup.deleter.time import UpdateTimeStepsDeleter
    from stonesoup.initiator.simple import MultiMeasurementInitiator
    from stonesoup.tracker.simple import MultiTargetTracker
    from stonesoup.updater.wrapper import DetectionAndTrackSwitchingUpdater
    from stonesoup.updater.chernoff import ChernoffUpdater
    from stonesoup.architecture.generator import NetworkArchitectureGenerator

    start_time = datetime.now().replace(microsecond=0)
    np.random.seed(2024)
    random.seed(2024)

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.005), ConstantVelocity(0.005)]
    )
    yps = range(0, 100, 10)
    truths = OrderedSet()
    ntruths = 3
    time_max = 60
    timesteps = [start_time + timedelta(seconds=k) for k in range(time_max)]

    xdirection = 1
    ydirection = 1
    for j in range(0, ntruths):
        truth = GroundTruthPath(
            [
                GroundTruthState(
                    [0, xdirection, yps[j], ydirection], timestamp=timesteps[0]
                )
            ],
            id=f"id{j}",
        )
        for k in range(1, time_max):
            truth.append(
                GroundTruthState(
                    transition_model.function(
                        truth[k - 1],
                        noise=True,
                        time_interval=timedelta(seconds=1),
                    ),
                    timestamp=timesteps[k],
                )
            )
        truths.add(truth)
        xdirection *= -1
        if j % 2 == 0:
            ydirection *= -1

    base_sensor = RadarRotatingBearingRange(
        position_mapping=(0, 2),
        noise_covar=np.array([[0.25 * np.radians(0.5) ** 2, 0], [0, 0.25 * 1**2]]),
        ndim_state=4,
        position=np.array([[10], [10]]),
        rpm=60,
        fov_angle=np.radians(360),
        dwell_centre=StateVector([0.0]),
        max_range=np.inf,
        resolution=Angle(np.radians(30)),
        seed=2024,
    )
    base_sensor.timestamp = start_time

    predictor = KalmanPredictor(transition_model)
    updater = ExtendedKalmanUpdater(measurement_model=None)
    hypothesiser = DistanceHypothesiser(
        predictor, updater, measure=Mahalanobis(), missed_distance=5
    )
    data_associator = GNNWith2DAssignment(hypothesiser)
    deleter = UpdateTimeStepsDeleter(2)
    initiator = MultiMeasurementInitiator(
        prior_state=GaussianState([[0], [0], [0], [0]], np.diag([0, 1, 0, 1])),
        measurement_model=None,
        deleter=deleter,
        data_associator=data_associator,
        updater=updater,
        min_points=4,
    )
    track_updater = ChernoffUpdater(None)
    detection_updater = ExtendedKalmanUpdater(None)
    detection_track_updater = DetectionAndTrackSwitchingUpdater(
        None, detection_updater, track_updater
    )
    base_tracker = MultiTargetTracker(
        initiator, deleter, None, data_associator, detection_track_updater
    )

    gen = NetworkArchitectureGenerator(
        "hierarchical",
        start_time,
        mean_degree=2,
        node_ratio=[3, 1, 2],
        base_tracker=base_tracker,
        base_sensor=base_sensor,
        sensor_max_distance=(30, 30),
        n_archs=4,
    )
    id_net_archs = gen.generate()

    network_arch = id_net_archs[0]
    information_arch = id_net_archs[1].information_arch
    network_steps = run_arch_sim(network_arch, truths, timesteps)
    information_steps = run_arch_sim(information_arch, truths, timesteps)

    network_top = network_arch.top_level_nodes.pop()
    information_top = information_arch.top_level_nodes.pop()
    network_siap = siap_averages(network_top, truths)
    information_siap = siap_averages(information_top, truths)
    network_arch.top_level_nodes.add(network_top)
    information_arch.top_level_nodes.add(information_top)

    network_arch_rm = id_net_archs[2]
    information_arch_rm = id_net_archs[3].information_arch

    rm = []
    for edge in network_arch_rm.edges:
        if "r3" in [node.label for node in edge.nodes]:
            rm.append(edge)
    for edge in rm:
        network_arch_rm.edges.remove(edge)

    rm = []
    for edge in information_arch_rm.edges:
        if ("sf0" in [node.label for node in edge.nodes]) and (
            "f1" in [node.label for node in edge.nodes]
        ):
            rm.append(edge)
    for edge in rm:
        information_arch_rm.edges.remove(edge)

    network_rm_steps = run_arch_sim_f1(network_arch_rm, truths, timesteps)
    information_rm_steps = run_arch_sim_f1(information_arch_rm, truths, timesteps)

    network_rm_top = [node for node in network_arch_rm.all_nodes if node.label == "f1"][0]
    information_rm_top = [
        node for node in information_arch_rm.all_nodes if node.label == "f1"
    ][0]
    network_rm_siap = siap_averages(network_rm_top, truths)
    information_rm_siap = siap_averages(information_rm_top, truths)

    truth_rows = [truth_snapshot(truths, ts) for ts in timesteps]

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_steps": time_max,
        "num_truths": ntruths,
        "truth": truth_rows,
        "network_steps": network_steps,
        "information_steps": information_steps,
        "network_rm_steps": network_rm_steps,
        "information_rm_steps": information_rm_steps,
        "network_siap": network_siap,
        "information_siap": information_siap,
        "network_rm_siap": network_rm_siap,
        "information_rm_siap": information_rm_siap,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

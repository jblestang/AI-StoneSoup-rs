#!/usr/bin/env python3
"""Export Information Filter tutorial fixtures (Stone Soup v1.9.1, seed 1991)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot6_information_filter.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot6_if_fixtures.rs"


def sv(state) -> list[float]:
    return [float(x) for x in state.state_vector.ravel()]


def write_rust(payload: dict) -> None:
    n = len(payload["track"])
    lines = [
        "// @generated by tools/python/export_lot6_information_filter.py — do not edit",
        f"pub const LOT6_NUM_STEPS: usize = {n};",
        f"pub const LOT6_PRIOR_MEAN: [f64; 4] = {payload['prior_mean']};",
        f"pub const LOT6_PRIOR_COV_DIAG: [f64; 4] = {payload['prior_cov_diag']};",
        "pub const LOT6_TRUTH: [[f64; 4]; LOT6_NUM_STEPS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT6_MEASUREMENTS: [[f64; 2]; LOT6_NUM_STEPS] = [")
    for row in payload["measurements"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT6_TRACK: [[f64; 4]; LOT6_NUM_STEPS] = [")
    for row in payload["track"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.models.measurement.linear import LinearGaussian
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.information import InformationKalmanPredictor
    from stonesoup.types.detection import Detection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.state import InformationState
    from stonesoup.types.track import Track
    from stonesoup.updater.information import InformationKalmanUpdater

    np.random.seed(1991)
    start_time = datetime.now().replace(microsecond=0)
    q = 0.05
    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(q), ConstantVelocity(q)]
    )
    truth = GroundTruthPath([GroundTruthState([20, 1, 20, 1], timestamp=start_time)])
    for k in range(1, 21):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1], noise=True, time_interval=timedelta(seconds=1)
                ),
                timestamp=start_time + timedelta(seconds=k),
            )
        )

    measurement_model = LinearGaussian(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.array([[5.0, 0.0], [0.0, 5.0]]),
    )
    measurements = []
    for state in truth:
        z = measurement_model.function(state, noise=True)
        measurements.append(
            Detection(z, timestamp=state.timestamp, measurement_model=measurement_model)
        )

    predictor = InformationKalmanPredictor(transition_model)
    updater = InformationKalmanUpdater(measurement_model)
    covar = np.diag([1.5, 0.5, 1.5, 0.5])
    precision = np.linalg.inv(covar)
    state = np.array([20.0, 1.0, 20.0, 1.0])
    information_state = precision @ state
    prior = InformationState(information_state, precision, timestamp=start_time)

    track = Track()
    for measurement in measurements:
        prediction = predictor.predict(prior, timestamp=measurement.timestamp)
        hypothesis = SingleHypothesis(prediction, measurement)
        post = updater.update(hypothesis)
        track.append(post)
        prior = track[-1]

    from stonesoup.measures import GaussianHellinger
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.types.state import GaussianState
    from stonesoup.updater.kalman import KalmanUpdater

    k_prior = GaussianState([[20], [1], [20], [1]], covar, timestamp=start_time)
    k_pred = KalmanPredictor(transition_model)
    k_upd = KalmanUpdater(measurement_model)
    k_track = Track()
    for measurement in measurements:
        pred = k_pred.predict(k_prior, timestamp=measurement.timestamp)
        hyp = SingleHypothesis(pred, measurement)
        post = k_upd.update(hyp)
        k_track.append(post)
        k_prior = post

    gh = GaussianHellinger()
    hellinger_sum = sum(
        gh(info.gaussian_state, kal) for info, kal in zip(track, k_track, strict=True)
    )

    track_gaussian = [sv(s.gaussian_state) for s in track]

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "seed": 1991,
        "q_x": q,
        "q_y": q,
        "dt_seconds": 1.0,
        "prior_mean": [20.0, 1.0, 20.0, 1.0],
        "prior_cov_diag": [1.5, 0.5, 1.5, 0.5],
        "measurement_noise_diag": [5.0, 5.0],
        "truth": [sv(s) for s in truth],
        "measurements": [m.state_vector.ravel().tolist() for m in measurements],
        "track": track_gaussian,
        "hellinger_sum_vs_kalman": float(hellinger_sum),
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("hellinger_sum_vs_kalman", hellinger_sum)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

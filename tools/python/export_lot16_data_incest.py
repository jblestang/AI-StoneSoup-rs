UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot16_data_incest.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot16_data_incest_fixtures.rs"
EXPORT_MODES = ("non_hierarchical", "hierarchical")


def track_means(tracks) -> list[list[float]]:
    rows = []
    for t in sorted(tracks, key=lambda tr: (tr.state_vector[0, 0], tr.state_vector[2, 0])):
        s = t.states[-1]
        rows.append([float(s.state_vector[i, 0]) for i in range(4)])
    return rows


def truth_snapshot(truths, timestep) -> list[list[float]]:
    rows = []
    for truth in sorted(truths, key=lambda t: t.id):
        for state in truth:
            if state.timestamp == timestep:
                rows.append([float(state.state_vector[i, 0]) for i in range(4)])
                break
    return rows


def reduce_tracks(tracks):
    from stonesoup.types.track import Track

    return {
        Track([s for s in track.last_timestamp_generator()])
        for track in tracks
    }


def fusion_node1_tracks(arch):
    return [node.tracks for node in arch.fusion_nodes if node.label == "Fusion Node 1"][0]


def run_arch_sim(arch, truths, timesteps):
    steps = []
    for time in timesteps:
        arch.measure(truths, noise=True)
        arch.propagate(time_increment=1)
        tracks = fusion_node1_tracks(arch)
        steps.append({"track_means": track_means(reduce_tracks(tracks))})
    return steps


def mean_cov_trace_at_time(tracks, timestep) -> float | None:
    import numpy as np

    states = sum(
        [[state for state in track.states if state.timestamp == timestep] for track in tracks],
        [],
    )
    if not states:
        return None
    trace_mean = float(np.mean([np.trace(s.covar) for s in states]))
    if math.isnan(trace_mean):
        return None
    return trace_mean


def cov_traces(tracks, timesteps) -> list[float | None]:
    return [mean_cov_trace_at_time(tracks, t) for t in timesteps]


def rust_mode_tag(mode: str) -> str:
    return {"non_hierarchical": "NH", "hierarchical": "H"}[mode]


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot16_data_incest.py — do not edit",
        f"pub const LOT16_NUM_STEPS: usize = {n};",
        f"pub const LOT16_NUM_TRUTHS: usize = {payload['num_truths']};",
        "pub const LOT16_TRUTH: [[[f64; 4]; LOT16_NUM_TRUTHS]; LOT16_NUM_STEPS] = [",
    ]
    for step in payload["truth"]:
        lines.append("    [")
        for row in step:
            lines.append(f"        {row},")
        lines.append("    ],")
    lines.append("];")

    for mode in EXPORT_MODES:
        tag = rust_mode_tag(mode)
        key = f"{mode}_steps"
        lines.append(f"pub const LOT16_{tag}_TRACK_OFFSETS: [usize; LOT16_NUM_STEPS + 1] = [")
        off = 0
        lines.append(f"    {off},")
        for s in payload[key]:
            off += len(s["track_means"])
            lines.append(f"    {off},")
        lines.append("];")
        lines.append(
            f"pub const LOT16_{tag}_TRACK_MEANS: [[f64; 4]; "
            f"LOT16_{tag}_TRACK_OFFSETS[LOT16_NUM_STEPS]] = ["
        )
        for s in payload[key]:
            for row in s["track_means"]:
                lines.append(f"    {row},")
        lines.append("];")
        traces = payload[f"{mode}_cov_trace"]
        lines.append(f"pub const LOT16_{tag}_MEAN_COV_TRACE: [f64; LOT16_NUM_STEPS] = [")
        for v in traces:
            if v is None:
                lines.append("    f64::NAN,")
            else:
                lines.append(f"    {v},")
        lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import copy
    import random

    import numpy as np
    from ordered_set import OrderedSet
    from stonesoup.architecture import InformationArchitecture
    from stonesoup.architecture.edge import Edge, Edges
    from stonesoup.architecture.node import FusionNode, SensorNode
    from stonesoup.base import Property
    from stonesoup.dataassociator.neighbour import GNNWith2DAssignment
    from stonesoup.deleter.error import CovarianceBasedDeleter
    from stonesoup.feeder.track import Tracks2GaussianDetectionFeeder
    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.initiator.simple import MultiMeasurementInitiator
    from stonesoup.measures import Mahalanobis
    from stonesoup.models.clutter import ClutterModel
    from stonesoup.models.measurement.base import MeasurementModel
    from stonesoup.models.measurement.linear import LinearGaussian
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.sensor.sensor import SimpleSensor
    from stonesoup.tracker.simple import MultiTargetTracker
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.state import CovarianceMatrix, GaussianState
    from stonesoup.updater.chernoff import ChernoffUpdater
    from stonesoup.updater.kalman import ExtendedKalmanUpdater
    from stonesoup.updater.wrapper import DetectionAndTrackSwitchingUpdater
    from stonesoup.architecture.edge import FusionQueue

    start_time = datetime.now().replace(microsecond=0)
    np.random.seed(1990)
    random.seed(1990)

    mm = LinearGaussian(
        ndim_state=4,
        mapping=[0, 2],
        noise_covar=CovarianceMatrix(np.diag([0.5, 0.5])),
        seed=6,
    )
    mm2 = LinearGaussian(
        ndim_state=4,
        mapping=[0, 2],
        noise_covar=CovarianceMatrix(np.diag([0.5, 0.5])),
        seed=12,
    )

    class DummySensor(SimpleSensor):
        measurement_model: MeasurementModel = Property(
            doc=":class:`~.MeasurementModel` to be used"
        )

        def is_detectable(self, *args, **kwargs):
            return True

        def is_clutter_detectable(self, *args, **kwargs):
            return True

    sensor1 = DummySensor(
        measurement_model=mm,
        position=np.array([[10], [-20]]),
        clutter_model=ClutterModel(
            clutter_rate=5, dist_params=((-100, 100), (-50, 60)), seed=6
        ),
    )
    sensor1.clutter_model.distribution = sensor1.clutter_model.random_state.uniform
    sensor2 = DummySensor(
        measurement_model=mm2,
        position=np.array([[10], [20]]),
        clutter_model=ClutterModel(
            clutter_rate=5, dist_params=((-100, 100), (-50, 60)), seed=12
        ),
    )
    sensor2.clutter_model.distribution = sensor2.clutter_model.random_state.uniform

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.005), ConstantVelocity(0.005)]
    )
    yps = range(0, 100, 10)
    truths = OrderedSet()
    ntruths = 3
    time_max = 60
    timesteps = [start_time + timedelta(seconds=k) for k in range(time_max)]

    xdirection = 1
    ydirection = 1
    for j in range(0, ntruths):
        truth = GroundTruthPath(
            [
                GroundTruthState(
                    [0, xdirection, yps[j], ydirection], timestamp=timesteps[0]
                )
            ],
            id=f"id{j}",
        )
        for k in range(1, time_max):
            truth.append(
                GroundTruthState(
                    transition_model.function(
                        truth[k - 1],
                        noise=True,
                        time_interval=timedelta(seconds=1),
                    ),
                    timestamp=timesteps[k],
                )
            )
        truths.add(truth)
        xdirection *= -1
        if j % 2 == 0:
            ydirection *= -1

    prior = GaussianState([[0], [1], [0], [1]], np.diag([1, 1, 1, 1]))
    predictor = KalmanPredictor(transition_model)
    updater = ExtendedKalmanUpdater(measurement_model=None)
    hypothesiser = DistanceHypothesiser(
        predictor, updater, measure=Mahalanobis(), missed_distance=5
    )
    data_associator = GNNWith2DAssignment(hypothesiser)
    deleter = CovarianceBasedDeleter(covar_trace_thresh=3)
    initiator = MultiMeasurementInitiator(
        prior_state=prior,
        measurement_model=None,
        deleter=deleter,
        data_associator=data_associator,
        updater=updater,
        min_points=5,
    )
    track_updater = ChernoffUpdater(None)
    detection_updater = ExtendedKalmanUpdater(None)
    detection_track_updater = DetectionAndTrackSwitchingUpdater(
        None, detection_updater, track_updater
    )
    track_tracker = MultiTargetTracker(
        initiator, deleter, None, data_associator, detection_track_updater
    )

    def make_nodes():
        sensornode1 = SensorNode(sensor=copy.deepcopy(sensor1), label="Sensor Node 1")
        sensornode1.sensor.clutter_model.distribution = (
            sensornode1.sensor.clutter_model.random_state.uniform
        )
        sensornode2 = SensorNode(sensor=copy.deepcopy(sensor2), label="Sensor Node 2")
        sensornode2.sensor.clutter_model.distribution = (
            sensornode2.sensor.clutter_model.random_state.uniform
        )
        f1_tracker = copy.deepcopy(track_tracker)
        f1_fq = FusionQueue()
        f1_tracker.detector = Tracks2GaussianDetectionFeeder(f1_fq)
        fusion_node1 = FusionNode(
            tracker=f1_tracker, fusion_queue=f1_fq, label="Fusion Node 1"
        )
        f2_tracker = copy.deepcopy(track_tracker)
        f2_fq = FusionQueue()
        f2_tracker.detector = Tracks2GaussianDetectionFeeder(f2_fq)
        fusion_node2 = FusionNode(
            tracker=f2_tracker, fusion_queue=f2_fq, label="Fusion Node 2"
        )
        return sensornode1, sensornode2, fusion_node1, fusion_node2

    s1, s2, f1, f2 = make_nodes()
    nh_edges = Edges(
        [
            Edge((s1, f1), edge_latency=0),
            Edge((s1, f2), edge_latency=0),
            Edge((s2, f2), edge_latency=0),
            Edge((f2, f1), edge_latency=0),
        ]
    )
    nh_arch = InformationArchitecture(nh_edges, current_time=start_time)
    nh_steps = run_arch_sim(nh_arch, truths, timesteps)
    nh_tracks = fusion_node1_tracks(nh_arch)
    nh_cov = cov_traces(nh_tracks, timesteps)

    s1b, s2b, f1b, f2b = make_nodes()
    h_edges = Edges(
        [
            Edge((s1b, f1b), edge_latency=0),
            Edge((s2b, f2b), edge_latency=0),
            Edge((f2b, f1b), edge_latency=0),
        ]
    )
    h_arch = InformationArchitecture(h_edges, current_time=start_time)
    h_steps = run_arch_sim(h_arch, truths, timesteps)
    h_tracks = fusion_node1_tracks(h_arch)
    h_cov = cov_traces(h_tracks, timesteps)

    truth_rows = [truth_snapshot(truths, ts) for ts in timesteps]
    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_steps": time_max,
        "num_truths": ntruths,
        "truth": truth_rows,
        "non_hierarchical_steps": nh_steps,
        "hierarchical_steps": h_steps,
        "non_hierarchical_cov_trace": nh_cov,
        "hierarchical_cov_trace": h_cov,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

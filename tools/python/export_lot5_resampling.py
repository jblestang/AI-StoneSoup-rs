#!/usr/bin/env python3
"""Export Resampling tutorial parity fixtures (Stone Soup v1.9.1, seed 1991).

Replays RNG draws from ``docs/tutorials/sampling/ResamplingTutorial.py`` up to each
resample call, then records particle state vectors after resampling.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot5_resampling.json"
RUST_FIXTURES = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot5_resampling_fixtures.rs"


def replay_tutorial_preamble(n_particles: int) -> None:
    """Consume RNG the same way as the notebook cells before the Stone Soup example."""
    import numpy as np

    _ = np.random.rand(5)
    _ = np.random.uniform(0, 1 / n_particles)
    s_lb = np.arange(n_particles) * (1 / n_particles)
    _ = np.random.uniform(s_lb, s_lb + (1 / n_particles))
    _ = np.random.rand(2)


def state_to_list(state) -> list[list[float]]:
    return state.state_vector.T.tolist()


def case_payload(name: str, state, nparts: int) -> dict:
    return {
        "name": name,
        "nparts": nparts,
        "state_dim": int(state.state_vector.shape[0]),
        "state_vector": state_to_list(state),
        "log_weight": state.log_weight.tolist(),
        "weight": [float(x) for x in state.weight.tolist()],
    }


def write_rust(cases: list[dict]) -> None:
    lines = [
        "// @generated by tools/python/export_lot5_resampling.py — do not edit",
        f"pub const LOT5_RESAMPLING_CASES: usize = {len(cases)};",
    ]
    for i, c in enumerate(cases):
        name = c["name"]
        nparts = c["nparts"]
        dim = c["state_dim"]
        lines.append(f'pub const LOT5_{i}_NAME: &str = "{name}";')
        lines.append(f"pub const LOT5_{i}_NPARTS: usize = {nparts};")
        lines.append(f"pub const LOT5_{i}_DIM: usize = {dim};")
        sv = c["state_vector"]
        lines.append(f"pub const LOT5_{i}_STATE: [[f64; {dim}]; {nparts}] = [")
        for row in sv:
            vals = ", ".join(str(float(x)) for x in row)
            lines.append(f"    [{vals}],")
        lines.append("];")
        lw = c["log_weight"]
        lw_s = ", ".join(str(float(x)) for x in lw)
        lines.append(f"pub const LOT5_{i}_LOG_W: [f64; {nparts}] = [{lw_s}];")
        lines.append("")
    RUST_FIXTURES.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.resampler.particle import (
        ESSResampler,
        MultinomialResampler,
        ResidualMethod,
        ResidualResampler,
        StratifiedResampler,
        SystematicResampler,
    )
    from stonesoup.types.particle import Particle

    n_particles = 5
    np.random.seed(1991)
    replay_tutorial_preamble(n_particles)

    equal_particles = [Particle(np.array([[float(i)]]), weight=1 / 5) for i in range(n_particles)]

    cases: list[dict] = []

    resampled = MultinomialResampler().resample(equal_particles)
    cases.append(case_payload("multinomial_equal_n5", resampled, n_particles))

    upsampled = MultinomialResampler().resample(equal_particles, nparts=10)
    cases.append(case_payload("multinomial_upsample_n10", upsampled, 10))

    np.random.seed(1991)
    replay_tutorial_preamble(n_particles)
    systematic = SystematicResampler().resample(equal_particles)
    cases.append(case_payload("systematic_equal_n5", systematic, n_particles))

    np.random.seed(1991)
    replay_tutorial_preamble(n_particles)
    stratified = StratifiedResampler().resample(equal_particles)
    cases.append(case_payload("stratified_equal_n5", stratified, n_particles))

    weights = np.array([1.0, 5.0, 1.5, 0.5, 2.0])
    norm = weights / weights.sum()
    weighted = [
        Particle(np.array([[float(i)]]), weight=float(w)) for i, w in enumerate(norm)
    ]
    np.random.seed(1991)
    replay_tutorial_preamble(n_particles)
    residual = ResidualResampler(residual_method=ResidualMethod.SYSTEMATIC).resample(weighted)
    cases.append(case_payload("residual_systematic_weighted_n5", residual, n_particles))

    np.random.seed(1991)
    replay_tutorial_preamble(n_particles)
    ess = ESSResampler(resampler=ResidualResampler(residual_method=ResidualMethod.SYSTEMATIC))
    ess_out = ess.resample(equal_particles)
    cases.append(case_payload("ess_residual_equal_n5", ess_out, n_particles))

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "numpy_seed": 1991,
        "cases": cases,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    write_rust(cases)
    print("wrote", OUT)
    print("wrote", RUST_FIXTURES)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Export ASD filter tutorial fixtures (Stone Soup v1.9.1, frozen truth + measurements)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot8_asd_filter.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot8_asd_fixtures.rs"
# Fixed epoch for reproducible timestamps (nanoseconds since Unix epoch).
START_EPOCH = datetime(2020, 1, 1, 0, 0, 0)


def write_rust(payload: dict) -> None:
    n_meas = len(payload["measurements"])
    n_upd = len(payload["updates"])
    lines = [
        "// @generated by tools/python/export_lot8_asd.py — do not edit",
        f"pub const LOT8_NUM_MEASUREMENTS: usize = {n_meas};",
        f"pub const LOT8_NUM_UPDATES: usize = {n_upd};",
        f"pub const LOT8_MAX_NSTEP: usize = {payload['max_nstep']};",
        f"pub const LOT8_PRIOR_MEAN: [f64; 4] = {payload['prior_mean']};",
        f"pub const LOT8_PRIOR_COV_DIAG: [f64; 4] = {payload['prior_cov_diag']};",
        f"pub const LOT8_Q: f64 = {payload['q']};",
        "pub const LOT8_MEASUREMENT_NOISE_DIAG: [f64; 2] = "
        f"{payload['measurement_noise_diag']};",
        "pub const LOT8_TRUTH_XY: [[f64; 2]; LOT8_NUM_MEASUREMENTS] = [",
    ]
    for row in payload["truth_xy"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT8_MEASUREMENT_TIMES_SEC: [i64; LOT8_NUM_MEASUREMENTS] = [")
    for t in payload["measurement_times_sec"]:
        lines.append(f"    {t},")
    lines.append("];")
    lines.append("pub const LOT8_MEASUREMENTS: [[f64; 2]; LOT8_NUM_MEASUREMENTS] = [")
    for row in payload["measurements"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT8_UPDATE_MEAS_INDEX: [usize; LOT8_NUM_UPDATES] = [")
    for row in payload["updates"]:
        lines.append(f"    {row['measurement_index']},")
    lines.append("];")
    lines.append("/// Per-update act-state (measurement timestamp index) mean and position cov block.")
    lines.append("pub const LOT8_UPDATE_ACT_MEAN: [[f64; 4]; LOT8_NUM_UPDATES] = [")
    for row in payload["updates"]:
        lines.append(f"    {row['act_mean']},")
    lines.append("];")
    lines.append("#[allow(dead_code)]")
    lines.append("pub const LOT8_UPDATE_ACT_COV: [[[f64; 4]; 4]; LOT8_NUM_UPDATES] = [")
    for row in payload["updates"]:
        lines.append("    [")
        for crow in row["act_cov"]:
            lines.append(f"        {crow},")
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from scipy.stats import multivariate_normal
    from stonesoup.models.measurement.linear import LinearGaussian
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.asd import ASDKalmanPredictor
    from stonesoup.types.detection import Detection
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.state import ASDGaussianState
    from stonesoup.types.track import Track
    from stonesoup.updater.asd import ASDKalmanUpdater

    np.random.seed(4242)
    start_time = START_EPOCH
    truth_xy = []
    for n in range(1, 202, 2):
        x = n - 100
        y = 1e-4 * (n - 100) ** 3
        varxy = np.array([[0.1, 0.0], [0.0, 0.1]])
        xy = np.random.multivariate_normal(np.array([x, y]), varxy)
        truth_xy.append([float(xy[0]), float(xy[1])])

    measurement_model = LinearGaussian(
        4,
        (0, 2),
        np.array([[5.0, 0.0], [0.0, 5.0]]),
    )
    measurements = []
    measurement_times_sec = []
    for i, (x, y) in enumerate(truth_xy):
        n = 1 + 2 * i
        ts = start_time + timedelta(seconds=n)
        measurement_times_sec.append(n)
        mx, my = multivariate_normal.rvs(
            np.array([x, y]), cov=np.diag([5.0, 5.0])
        )
        measurements.append(
            Detection([mx, my], timestamp=ts, measurement_model=measurement_model)
        )

    q = 0.2
    transition_model = CombinedLinearGaussianTransitionModel(
        (ConstantVelocity(q), ConstantVelocity(q))
    )
    predictor = ASDKalmanPredictor(transition_model)
    updater = ASDKalmanUpdater(measurement_model)

    prior = ASDGaussianState(
        multi_state_vector=[[-100.0], [0.0], [-100.0], [0.0]],
        timestamps=start_time,
        multi_covar=np.diag([1.0, 1.0, 1.0, 1.0]),
        max_nstep=30,
    )

    updates = []
    track = Track()
    for i in range(0, len(measurements)):
        if i > 10:
            if i % 10 != 0:
                continue
            m = measurements[i]
            prediction = predictor.predict(prior, timestamp=m.timestamp)
            hypothesis = SingleHypothesis(prediction, m)
            post = updater.update(hypothesis)
            track.append(post)
            prior = track[-1]
            t_index = post.timestamps.index(m.timestamp)
            act = post[t_index]
            updates.append(
                {
                    "measurement_index": i,
                    "act_mean": [float(x) for x in act.state_vector.ravel()],
                    "act_cov": act.covar.tolist(),
                }
            )
            for j in range(9, 0, -1):
                m = measurements[i - j]
                prediction = predictor.predict(prior, timestamp=m.timestamp)
                hypothesis = SingleHypothesis(prediction, m)
                post = updater.update(hypothesis)
                track.append(post)
                prior = track[-1]
                t_index = post.timestamps.index(m.timestamp)
                act = post[t_index]
                updates.append(
                    {
                        "measurement_index": i - j,
                        "act_mean": [float(x) for x in act.state_vector.ravel()],
                        "act_cov": act.covar.tolist(),
                    }
                )
        else:
            m = measurements[i]
            prediction = predictor.predict(prior, timestamp=m.timestamp)
            hypothesis = SingleHypothesis(prediction, m)
            post = updater.update(hypothesis)
            track.append(post)
            prior = track[-1]
            t_index = post.timestamps.index(m.timestamp)
            act = post[t_index]
            updates.append(
                {
                    "measurement_index": i,
                    "act_mean": [float(x) for x in act.state_vector.ravel()],
                    "act_cov": act.covar.tolist(),
                }
            )

    assert len(updates) == 101, len(updates)

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "seed_truth": 4242,
        "start_epoch_iso": START_EPOCH.isoformat(),
        "q": q,
        "max_nstep": 30,
        "prior_mean": [-100.0, 0.0, -100.0, 0.0],
        "prior_cov_diag": [1.0, 1.0, 1.0, 1.0],
        "measurement_noise_diag": [5.0, 5.0],
        "truth_xy": truth_xy,
        "measurement_times_sec": measurement_times_sec,
        "measurements": [m.state_vector.ravel().tolist() for m in measurements],
        "updates": updates,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("num_updates", len(updates))
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

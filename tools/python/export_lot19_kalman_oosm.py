#!/usr/bin/env python3
"""Export Lot 19 — Kalman filter OOSM example (three trackers)."""
from __future__ import annotations

import hashlib
import json
from copy import deepcopy
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot19_kalman_oosm.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot19_kalman_oosm_fixtures.rs"


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def write_rust(payload: dict) -> None:
    n = payload["num_loops"]
    lines = [
        "// @generated by tools/python/export_lot19_kalman_oosm.py — do not edit",
        f"pub const LOT19_NUM_TRUTHS: usize = {payload['num_truths']};",
        f"pub const LOT19_NUM_LOOPS: usize = {n};",
        f"pub const LOT19_DELAY_SEC: i64 = {payload['delay_sec']};",
        f"pub const LOT19_Q: f64 = {payload['q']};",
        "pub const LOT19_TRUTH: [[f64; 4]; LOT19_NUM_TRUTHS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    for tag, key in (
        ("T1", "tracker1"),
        ("T2", "tracker2"),
        ("T3", "tracker3"),
    ):
        lines.append(f"pub const LOT19_{tag}_TRACK: [[f64; 4]; LOT19_NUM_LOOPS] = [")
        for row in payload[key]:
            lines.append(f"    {row},")
        lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.models.measurement.nonlinear import CartesianToBearingRange
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kalman import ExtendedKalmanPredictor
    from stonesoup.types.detection import Detection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.state import GaussianState
    from stonesoup.types.track import Track
    from stonesoup.updater.kalman import ExtendedKalmanUpdater

    start_time = datetime.now().replace(microsecond=0)
    np.random.seed(2000)
    num_steps = 50

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.5), ConstantVelocity(0.5)]
    )
    truth = GroundTruthPath([GroundTruthState([0, 1, 0, 1], timestamp=start_time)])
    for k in range(1, num_steps):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1],
                    noise=True,
                    time_interval=timedelta(seconds=2),
                ),
                timestamp=start_time + timedelta(seconds=2 * k),
            )
        )

    measurement_model_1 = CartesianToBearingRange(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([np.radians(3), 20]),
        translation_offset=np.array([[-60], [0]]),
    )
    measurement_model_2 = CartesianToBearingRange(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([np.radians(3), 20]),
        translation_offset=np.array([[-150], [60]]),
    )

    measurements1 = []
    measurements2 = []
    truth_rows = []
    for state in truth:
        truth_rows.append(state_mean(state))
        measurements1.append(
            Detection(
                measurement_model_1.function(state, noise=True),
                timestamp=state.timestamp,
                measurement_model=measurement_model_1,
            )
        )
        measurements2.append(
            Detection(
                measurement_model_2.function(state, noise=True),
                timestamp=state.timestamp + timedelta(seconds=5),
                measurement_model=measurement_model_2,
            )
        )

    predictor = ExtendedKalmanPredictor(transition_model)
    updater1 = ExtendedKalmanUpdater(measurement_model_1)
    updater2 = ExtendedKalmanUpdater(measurement_model_2)

    prior1 = GaussianState(
        state_vector=np.array([0, 1, 0, 1]),
        covar=np.diag([1, 1, 1, 1]),
        timestamp=start_time,
    )
    prior2 = GaussianState(
        state_vector=np.array([0, 1, 0, 1]),
        covar=np.diag([1, 1, 1, 1]),
        timestamp=start_time + timedelta(seconds=5),
    )
    prior3 = deepcopy(prior1)

    delay = measurements2[0].timestamp - measurements1[0].timestamp
    track1 = Track(prior1)
    track2 = Track(prior2)
    track3 = Track(prior3)

    t1_rows = []
    t2_rows = []
    t3_rows = []
    timestep_delay = 0

    for k in range(num_steps + 5):
        check_delay = timedelta(seconds=k)
        if check_delay == delay:
            timestep_delay = k

        if check_delay < delay:
            prediction = predictor.predict(prior1, timestamp=measurements1[k].timestamp)
            hypothesis = SingleHypothesis(prediction, measurements1[k])
            post = updater1.update(hypothesis)
            track1.append(post)
            prior1 = track1[-1]
        else:
            if k < num_steps:
                prediction = predictor.predict(prior1, timestamp=measurements1[k].timestamp)
                hypothesis = SingleHypothesis(prediction, measurements1[k])
                post = updater1.update(hypothesis)
                track1.append(post)
                prediction = predictor.predict(
                    prior1, timestamp=measurements2[k - timestep_delay].timestamp
                )
                hypothesis = SingleHypothesis(prediction, measurements2[k - timestep_delay])
                post = updater2.update(hypothesis)
                track1.append(post)
                prior1 = track1[-1]
            else:
                prediction = predictor.predict(
                    prior1, timestamp=measurements2[k - timestep_delay].timestamp
                )
                hypothesis = SingleHypothesis(prediction, measurements2[k - timestep_delay])
                post = updater2.update(hypothesis)
                track1.append(post)
                prior1 = track1[-1]

        if check_delay >= delay:
            prediction = predictor.predict(
                prior2,
                timestamp=measurements1[k - timestep_delay].timestamp + delay,
            )
            hypothesis = SingleHypothesis(prediction, measurements1[k - timestep_delay])
            post = updater1.update(hypothesis)
            track2.append(post)
            prediction = predictor.predict(
                prior2, timestamp=measurements2[k - timestep_delay].timestamp
            )
            hypothesis = SingleHypothesis(prediction, measurements2[k - timestep_delay])
            post = updater2.update(hypothesis)
            track2.append(post)
            prior2 = track2[-1]

        if k < num_steps:
            prediction = predictor.predict(prior3, timestamp=measurements1[k].timestamp)
            hypothesis = SingleHypothesis(prediction, measurements1[k])
            post = updater1.update(hypothesis)
            track3.append(post)
            prior3 = track3[-1]

        t1_rows.append(state_mean(track1[-1]))
        t2_rows.append(state_mean(track2[-1]))
        t3_rows.append(state_mean(track3[-1]))

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_truths": num_steps,
        "num_loops": num_steps + 5,
        "delay_sec": int(delay.total_seconds()),
        "q": 0.5,
        "truth": truth_rows,
        "tracker1": t1_rows,
        "tracker2": t2_rows,
        "tracker3": t3_rows,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

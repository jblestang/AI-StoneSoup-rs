#!/usr/bin/env python3
"""Export AKKF tutorial oracle fixtures (Stone Soup v1.9.1 @ pinned SHA)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot9_akkf_filter.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot9_akkf_fixtures.rs"


def write_rust(payload: dict) -> None:
    n = payload["num_particles"]
    steps = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot9_akkf.py — do not edit",
        f"pub const LOT9_NUM_PARTICLES: usize = {n};",
        f"pub const LOT9_NUM_STEPS: usize = {steps};",
        f"pub const LOT9_Q: f64 = {payload['q']};",
        f"#[allow(dead_code)]",
        f"pub const LOT9_BEARING_NOISE_VAR: f64 = {payload['bearing_noise_var']};",
        "pub const LOT9_TRUTH_XY: [[f64; 2]; LOT9_NUM_STEPS] = [",
    ]
    for row in payload["truth_xy"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT9_BEARINGS: [f64; LOT9_NUM_STEPS] = [")
    for b in payload["bearings"]:
        lines.append(f"    {b},")
    lines.append("];")
    lines.append("pub const LOT9_REF_MEAN: [[f64; 4]; LOT9_NUM_STEPS] = [")
    for row in payload["ref_mean"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from scipy.stats import multivariate_normal
    from stonesoup.kernel import QuadraticKernel
    from stonesoup.models.measurement.nonlinear import Cartesian2DToBearing
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kernel import AdaptiveKernelKalmanPredictor
    from stonesoup.types.array import StateVectors
    from stonesoup.types.detection import Detection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.state import KernelParticleState
    from stonesoup.types.track import Track
    from stonesoup.updater.kernel import AdaptiveKernelKalmanUpdater

    np.random.seed(50)
    start_time = datetime.now().replace(microsecond=0)
    q_x = q_y = 1e-4
    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(q_x), ConstantVelocity(q_y)]
    )
    truth = GroundTruthPath(
        [GroundTruthState([-0.3, 0.001, 0.7, -0.055], timestamp=start_time)]
    )
    num_steps = 30
    for k in range(1, num_steps):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1], noise=True, time_interval=timedelta(seconds=1)
                ),
                timestamp=start_time + timedelta(seconds=k),
            )
        )

    measurement_model = Cartesian2DToBearing(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.array([[0.005**2]]),
    )
    measurements = []
    for state in truth:
        measurement = measurement_model.function(state, noise=True)
        measurements.append(
            Detection(
                measurement,
                timestamp=state.timestamp,
                measurement_model=measurement_model,
            )
        )

    number_particles = 30
    np.random.seed(50)
    samples = multivariate_normal.rvs(
        np.squeeze(truth[0].state_vector),
        np.diag([0.1, 0.005, 0.1, 0.01]) ** 2,
        size=number_particles,
    )
    prior = KernelParticleState(
        state_vector=StateVectors(samples.T),
        weight=np.array([1 / number_particles] * number_particles),
        timestamp=start_time,
    )

    predictor = AdaptiveKernelKalmanPredictor(
        transition_model=transition_model, kernel=QuadraticKernel(c=1, ialpha=1)
    )
    updater = AdaptiveKernelKalmanUpdater(
        measurement_model=measurement_model, kernel=QuadraticKernel(c=1, ialpha=1)
    )

    ref_mean = []
    track = Track()
    for measurement in measurements:
        prediction = predictor.predict(prior, timestamp=measurement.timestamp)
        hypothesis = SingleHypothesis(prediction, measurement)
        post = updater.update(hypothesis)
        track.append(post)
        prior = track[-1]
        m = prior.state_vector @ prior.weight[:, np.newaxis]
        ref_mean.append([float(v) for v in m.ravel()])

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_particles": number_particles,
        "num_steps": num_steps,
        "q": q_x,
        "bearing_noise_var": 0.005**2,
        "truth_xy": [[float(s.state_vector[0, 0]), float(s.state_vector[2, 0])] for s in truth],
        "bearings": [float(m.state_vector[0, 0]) for m in measurements],
        "ref_mean": ref_mean,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Export Lot 21 — OOSM Algorithm C (inverse-time dynamics, UKF+JPDA)."""
from __future__ import annotations

import hashlib
import json
from copy import deepcopy
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot21_oosm_algorithm.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot21_oosm_algorithm_fixtures.rs"


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot21_oosm_algorithm.py — do not edit",
        f"pub const LOT21_NUM_STEPS: usize = {n};",
        f"pub const LOT21_NUM_TARGETS: usize = {payload['num_targets']};",
        "pub const LOT21_TRUTH_T0: [[f64; 4]; LOT21_NUM_STEPS] = [",
    ]
    for row in payload["truth_t0"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT21_TRUTH_T1: [[f64; 4]; LOT21_NUM_STEPS] = [")
    for row in payload["truth_t1"]:
        lines.append(f"    {row},")
    lines.append("];")
    for tag, key in (
        ("OOSM_T0", "oosm_t0"),
        ("OOSM_T1", "oosm_t1"),
        ("NOOOSM_T0", "no_oosm_t0"),
        ("NOOOSM_T1", "no_oosm_t1"),
    ):
        lines.append(f"pub const LOT21_{tag}_TRACK: [[f64; 4]; LOT21_NUM_STEPS] = [")
        for row in payload[key]:
            lines.append(f"    {row},")
        lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.dataassociator.probability import JPDA
    from stonesoup.hypothesiser.probability import PDAHypothesiser
    from stonesoup.models.measurement.nonlinear import CartesianToBearingRange
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kalman import UnscentedKalmanPredictor
    from stonesoup.types.detection import Clutter, TrueDetection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.state import GaussianState, State, StateVector
    from stonesoup.types.track import Track
    from stonesoup.updater.kalman import UnscentedKalmanUpdater

    start_time = datetime.now().replace(microsecond=0)
    np.random.seed(2000)
    num_steps = 65
    scans_delay = 5
    extra_delay = 2
    prob_detect = 0.90
    lambda_v = 2
    v_bounds = np.array([[-1, 450], [-130, 130]])
    clutter_spatial_density = lambda_v / (
        np.prod(v_bounds[:, 0] - v_bounds[:, 1])
    )

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(1e-4), ConstantVelocity(1e-4)]
    )
    timestamps = [start_time]
    truths = set()

    truth0 = GroundTruthPath(
        [GroundTruthState([0, 1, -100, 0.3], timestamp=start_time)]
    )
    for k in range(1, num_steps):
        timeid = start_time + timedelta(seconds=scans_delay * k)
        truth0.append(
            GroundTruthState(
                transition_model.function(
                    truth0[k - 1],
                    noise=True,
                    time_interval=timedelta(seconds=scans_delay),
                ),
                timestamp=timeid,
            )
        )
        timestamps.append(timeid)
    truths.add(truth0)

    truth1 = GroundTruthPath(
        [GroundTruthState([0, 1, 100, -0.3], timestamp=start_time)]
    )
    for k in range(1, num_steps):
        truth1.append(
            GroundTruthState(
                transition_model.function(
                    truth1[k - 1],
                    noise=True,
                    time_interval=timedelta(seconds=scans_delay),
                ),
                timestamp=start_time + timedelta(seconds=scans_delay * k),
            )
        )
    truths.add(truth1)
    truth_list = [truth0, truth1]

    sensor_1_mm = CartesianToBearingRange(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([np.radians(5), 10]),
    )
    sensor_2_mm = deepcopy(sensor_1_mm)

    scan_s1, scan_s2 = [], []
    for k in range(num_steps):
        detections1 = set()
        detections2 = set()
        delay = extra_delay if (not k % 5 and k > 0) else 0

        for truth in truths:
            if np.random.rand() <= prob_detect:
                measurement = sensor_1_mm.function(truth[k], noise=True)
                detections1.add(
                    TrueDetection(
                        state_vector=measurement,
                        groundtruth_path=truth,
                        timestamp=truth[k].timestamp,
                    )
                )
                measurement = sensor_2_mm.function(truth[k], noise=True)
                detections2.add(
                    TrueDetection(
                        state_vector=measurement,
                        groundtruth_path=truth,
                        timestamp=truth[k].timestamp + timedelta(seconds=delay),
                    )
                )

        for _ in range(np.random.poisson(lambda_v)):
            x1 = np.random.uniform(*v_bounds[0, :])
            y1 = np.random.uniform(*v_bounds[1, :])
            x2 = np.random.uniform(*v_bounds[0, :])
            y2 = np.random.uniform(*v_bounds[1, :])
            state1 = State(
                state_vector=StateVector(
                    [x1, truth0.state_vector[1], y1, truth0.state_vector[3]]
                )
            )
            state2 = State(
                state_vector=StateVector(
                    [x2, truth0.state_vector[1], y2, truth0.state_vector[3]]
                )
            )
            detections1.add(
                Clutter(
                    sensor_1_mm.function(state1, noise=False),
                    timestamp=truth0[k].timestamp,
                    measurement_model=sensor_1_mm,
                )
            )
            detections2.add(
                Clutter(
                    sensor_2_mm.function(state2, noise=False),
                    timestamp=truth0[k].timestamp + timedelta(seconds=delay),
                    measurement_model=sensor_2_mm,
                )
            )

        scan_s1.append(detections1)
        scan_s2.append(detections2)

    predictor = UnscentedKalmanPredictor(transition_model)
    updater = UnscentedKalmanUpdater(measurement_model=sensor_1_mm)
    hypothesiser = PDAHypothesiser(
        predictor=predictor,
        updater=updater,
        clutter_spatial_density=clutter_spatial_density,
        prob_detect=prob_detect,
    )
    data_associator = JPDA(hypothesiser=hypothesiser)

    priori1 = GaussianState(
        state_vector=np.array([0, 1, -100, 0.3]),
        covar=np.diag([1, 1, 1, 1]),
        timestamp=start_time,
    )
    priori2 = GaussianState(
        state_vector=np.array([0, 1, 100, -0.3]),
        covar=np.diag([1, 1, 1, 1]),
        timestamp=start_time,
    )
    oosm_tracks = (Track([priori1]), Track([priori2]))
    no_oosm_tracks = (Track([deepcopy(priori1)]), Track([deepcopy(priori2)]))

    oosm_t0, oosm_t1, no_oosm_t0, no_oosm_t1 = [], [], [], []

    for k in range(len(scan_s1)):
        for detections_1, detections_2 in zip(scan_s1[k], scan_s2[k]):
            if timestamps[k] != detections_2.timestamp:
                predicted_location = State(
                    state_vector=StateVector(
                        sensor_2_mm.inverse_function(detections_2, noise=False)
                    ),
                    timestamp=timestamps[k],
                )
                oos_location = transition_model.function(
                    predicted_location,
                    noise=False,
                    time_interval=detections_2.timestamp - timestamps[k],
                )
                pseudo_state = State(
                    state_vector=StateVector(oos_location),
                    timestamp=timestamps[k],
                )
                if isinstance(detections_2, TrueDetection):
                    pseudo_meas = TrueDetection(
                        state_vector=sensor_2_mm.function(pseudo_state, noise=False),
                        groundtruth_path=detections_2.groundtruth_path,
                        measurement_model=sensor_2_mm,
                        timestamp=pseudo_state.timestamp,
                    )
                else:
                    pseudo_meas = Clutter(
                        state_vector=sensor_2_mm.function(pseudo_state, noise=False),
                        measurement_model=sensor_2_mm,
                        timestamp=pseudo_state.timestamp,
                    )
                detections = [detections_1, pseudo_meas]
            else:
                detections = [detections_1, detections_2]

            associations = data_associator.associate(
                oosm_tracks, detections, timestamps[k]
            )
            for track, hypotheses in associations.items():
                for hypothesis in hypotheses:
                    if not hypothesis:
                        track.append(hypothesis.prediction)
                    else:
                        post = updater.update(hypothesis)
                        track.append(post)

        oosm_t0.append(state_mean(oosm_tracks[0][-1]))
        oosm_t1.append(state_mean(oosm_tracks[1][-1]))

    for k in range(len(scan_s1)):
        for detections_1, detections_2 in zip(scan_s1[k], scan_s2[k]):
            if timestamps[k] == detections_2.timestamp:
                detections = [detections_1, detections_2]
                associations = data_associator.associate(
                    no_oosm_tracks, detections, timestamps[k]
                )
                for track, hypotheses in associations.items():
                    for hyp in hypotheses:
                        if not hyp:
                            track.append(hyp.prediction)
                        else:
                            post = updater.update(hyp)
                            track.append(post)

        no_oosm_t0.append(state_mean(no_oosm_tracks[0][-1]))
        no_oosm_t1.append(state_mean(no_oosm_tracks[1][-1]))

    truth_t0 = [state_mean(truth0[k]) for k in range(num_steps)]
    truth_t1 = [state_mean(truth1[k]) for k in range(num_steps)]

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_steps": num_steps,
        "num_targets": 2,
        "truth_t0": truth_t0,
        "truth_t1": truth_t1,
        "oosm_t0": oosm_t0,
        "oosm_t1": oosm_t1,
        "no_oosm_t0": no_oosm_t0,
        "no_oosm_t1": no_oosm_t1,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

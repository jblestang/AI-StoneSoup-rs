#!/usr/bin/env python3
"""Export GM-PHD tutorial fixtures (Stone Soup v1.9.1, fixed RNG)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot7_gm_phd.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot7_gm_phd_fixtures.rs"
SEED = 42


def sv(state) -> list[float]:
    return [float(x) for x in state.state_vector.ravel()]


def comp_dict(c) -> dict:
    tag = c.tag
    if tag is None:
        tag_s = "null"
    elif tag == "birth":
        tag_s = "birth"
    else:
        tag_s = str(tag)
    return {
        "weight": float(c.weight),
        "mean": sv(c),
        "tag": tag_s,
    }


def write_rust(payload: dict) -> None:
    n = payload["num_steps"]
    lines = [
        "// @generated by tools/python/export_lot7_gm_phd.py — do not edit",
        f"pub const LOT7_NUM_STEPS: usize = {n};",
        f"pub const LOT7_SEED: u64 = {payload['seed']};",
        f"pub const LOT7_PROB_DETECTION: f64 = {payload['prob_detection']};",
        f"pub const LOT7_CLUTTER_RATE: f64 = {payload['clutter_rate']};",
        f"pub const LOT7_DEATH_PROB: f64 = {payload['death_probability']};",
        f"pub const LOT7_BIRTH_PROB: f64 = {payload['birth_probability']};",
        f"pub const LOT7_CLUTTER_DENSITY: f64 = {payload['clutter_spatial_density']};",
        f"pub const LOT7_MERGE_THRESHOLD: f64 = {float(payload['merge_threshold'])};",
        f"pub const LOT7_PRUNE_THRESHOLD: f64 = {payload['prune_threshold']};",
        f"pub const LOT7_STATE_THRESHOLD: f64 = {payload['state_threshold']};",
        f"pub const LOT7_MISSED_DISTANCE: f64 = {payload['missed_distance']};",
        f"pub const LOT7_INIT_COV_DIAG: [f64; 4] = {payload['init_cov_diag']};",
        f"pub const LOT7_INIT_WEIGHT: f64 = {payload['init_weight']};",
        f"pub const LOT7_BIRTH_COV_DIAG: [f64; 4] = {payload['birth_cov_diag']};",
        f"pub const LOT7_BIRTH_WEIGHT: f64 = {payload['birth_weight']};",
        "pub const LOT7_START_TRUTHS: [[f64; 4]; 3] = [",
    ]
    for row in payload["start_truths"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    lines.append("pub struct Lot7MeasurementSet {")
    lines.append("    pub n: usize,")
    lines.append("    pub xy: [[f64; 2]; 64],")
    lines.append("}")
    lines.append("")
    lines.append("pub const LOT7_MEASUREMENTS: [Lot7MeasurementSet; LOT7_NUM_STEPS] = [")
    for step in payload["measurements"]:
        n_det = len(step)
        lines.append(f"    Lot7MeasurementSet {{ n: {n_det}, xy: [")
        for i, xy in enumerate(step):
            comma = "," if i < 63 else ""
            if i >= 64:
                raise RuntimeError("too many detections in a step")
            lines.append(f"        {xy}{comma}")
        for _ in range(n_det, 64):
            lines.append("        [0.0, 0.0],")
        lines.append("    ] },")
    lines.append("];")
    lines.append("")
    lines.append("pub struct Lot7Component {")
    lines.append("    pub weight: f64,")
    lines.append("    pub mean: [f64; 4],")
    lines.append("    pub tag: u32, // 0=none/new, 1=birth, else uuid hash truncated")
    lines.append("}")
    lines.append("")
    lines.append("pub struct Lot7ReducedStep {")
    lines.append("    pub n: usize,")
    lines.append("    pub components: [Lot7Component; 64],")
    lines.append("}")
    lines.append("")
    lines.append("pub const LOT7_REDUCED: [Lot7ReducedStep; LOT7_NUM_STEPS] = [")
    for step in payload["reduced_by_step"]:
        n_c = len(step)
        lines.append(f"    Lot7ReducedStep {{ n: {n_c}, components: [")
        for i, c in enumerate(step):
            tag = c["tag"]
            if tag == "birth":
                tag_u = 1
            elif tag == "null":
                tag_u = 0
            else:
                tag_u = int(tag, 16) if len(tag) <= 8 else int(hashlib.md5(tag.encode()).hexdigest()[:8], 16)
            lines.append(
                f"        Lot7Component {{ weight: {c['weight']}, mean: {c['mean']}, tag: {tag_u} }},"
            )
        max_c = 64
        if n_c > max_c:
            raise RuntimeError(f"step has {n_c} reduced components (max {max_c})")
        for _ in range(n_c, max_c):
            lines.append(
                "        Lot7Component { weight: 0.0, mean: [0.0; 4], tag: 0 },"
            )
        lines.append("    ] },")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from ordered_set import OrderedSet
    from scipy.stats import uniform

    from stonesoup.hypothesiser.distance import DistanceHypothesiser
    from stonesoup.hypothesiser.gaussianmixture import GaussianMixtureHypothesiser
    from stonesoup.measures import Mahalanobis
    from stonesoup.mixturereducer.gaussianmixture import GaussianMixtureReducer
    from stonesoup.models.measurement.linear import LinearGaussian
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.types.array import CovarianceMatrix
    from stonesoup.types.detection import Clutter, TrueDetection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.state import TaggedWeightedGaussianState
    from stonesoup.types.track import Track
    from stonesoup.updater.kalman import KalmanUpdater
    from stonesoup.updater.pointprocess import PHDUpdater

    np.random.seed(SEED)
    start_time = datetime.now().replace(microsecond=0)
    transition_model = CombinedLinearGaussianTransitionModel(
        (ConstantVelocity(0.3), ConstantVelocity(0.3))
    )
    number_steps = 20
    death_probability = 0.005
    birth_probability = 0.2

    truths = OrderedSet()
    current_truths = set()
    initial_truths = []
    for _i in range(3):
        x, y = np.random.uniform(-30, 30, 2)
        x_vel, y_vel = np.random.rand(2) * 2 - 1
        state = GroundTruthState([x, x_vel, y, y_vel], timestamp=start_time)
        truth = GroundTruthPath([state])
        current_truths.add(truth)
        truths.add(truth)
        initial_truths.append(truth)

    covar = CovarianceMatrix(np.diag([10, 5, 10, 5]))
    tracks = []
    for truth in initial_truths:
        tracks.append(
            Track(
                TaggedWeightedGaussianState(
                    state_vector=truth[0].state_vector,
                    covar=covar**2,
                    weight=0.25,
                    tag=TaggedWeightedGaussianState.BIRTH,
                    timestamp=start_time,
                )
            )
        )
    reduced_states = [track[-1] for track in tracks]
    birth_covar = CovarianceMatrix(np.diag([1000, 2, 1000, 2]))
    birth_component = TaggedWeightedGaussianState(
        state_vector=[0, 0, 0, 0],
        covar=birth_covar**2,
        weight=0.25,
        tag="birth",
        timestamp=start_time,
    )

    for k in range(number_steps):
        for truth in current_truths.copy():
            if np.random.rand() <= death_probability:
                current_truths.remove(truth)
        for truth in current_truths:
            updated_state = GroundTruthState(
                transition_model.function(
                    truth[-1], noise=True, time_interval=timedelta(seconds=1)
                ),
                timestamp=start_time + timedelta(seconds=k),
            )
            truth.append(updated_state)
        for _ in range(np.random.poisson(birth_probability)):
            x, y = np.random.rand(2) * [120, 120]
            x_vel, y_vel = np.random.rand(2) * 2 - 1
            state = GroundTruthState(
                [x, x_vel, y, y_vel], timestamp=start_time + timedelta(seconds=k)
            )
            truth = GroundTruthPath([state])
            current_truths.add(truth)
            truths.add(truth)

    measurement_model = LinearGaussian(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.array([[0.75, 0], [0, 0.75]]),
    )
    probability_detection = 0.9
    clutter_rate = 3.0
    all_measurements = []
    for k in range(number_steps):
        measurement_list = []
        timestamp = start_time + timedelta(seconds=k)
        for truth in truths:
            try:
                truth_state = truth[timestamp]
            except IndexError:
                continue
            if np.random.rand() <= probability_detection:
                measurement = measurement_model.function(truth_state, noise=True)
                measurement_list.append(
                    TrueDetection(
                        state_vector=measurement,
                        groundtruth_path=truth,
                        timestamp=truth_state.timestamp,
                        measurement_model=measurement_model,
                    )
                )
        for _ in range(np.random.poisson(clutter_rate)):
            x = uniform.rvs(-200, 400)
            y = uniform.rvs(-200, 400)
            measurement_list.append(
                Clutter(
                    np.array([[x], [y]]),
                    timestamp=timestamp,
                    measurement_model=measurement_model,
                )
            )
        all_measurements.append(measurement_list)

    kalman_updater = KalmanUpdater(measurement_model)
    meas_range = np.array([[-1, 1], [-1, 1]]) * 200
    clutter_spatial_density = clutter_rate / np.prod(np.diff(meas_range))
    updater = PHDUpdater(
        kalman_updater,
        clutter_spatial_density=clutter_spatial_density,
        prob_detection=probability_detection,
        prob_survival=1 - death_probability,
    )
    kalman_predictor = KalmanPredictor(transition_model)
    base_hypothesiser = DistanceHypothesiser(
        kalman_predictor, kalman_updater, Mahalanobis(), missed_distance=3
    )
    hypothesiser = GaussianMixtureHypothesiser(
        base_hypothesiser, order_by_detection=True
    )
    merge_threshold = 5
    prune_threshold = 1e-8
    reducer = GaussianMixtureReducer(
        prune_threshold=prune_threshold,
        pruning=True,
        merge_threshold=merge_threshold,
        merging=True,
    )
    state_threshold = 0.25
    reduced_by_step = []
    pre_reduce_by_step = []
    pre_reduce_snapshots = []
    tag_map = {}

    def tag_key(t):
        if t is None:
            return "null"
        if t == "birth" or t == TaggedWeightedGaussianState.BIRTH:
            return "birth"
        return str(t)

    def sort_components(states):
        return sorted(states, key=lambda s: (-s.weight, sv(s)[0], sv(s)[2]))

    for n, measurements in enumerate(all_measurements):
        current_state = list(reduced_states)
        if measurements:
            time = measurements[0].timestamp
        else:
            time = start_time + timedelta(seconds=n)
        birth_component.timestamp = time
        current_state.append(birth_component)
        hypotheses = hypothesiser.hypothesise(
            current_state, measurements, timestamp=time, order_by_detection=True
        )
        updated_states = updater.update(hypotheses)
        pre_reduce_by_step.append(len(updated_states.components))
        if n == 1:
            snap = []
            for c in updated_states.components:
                snap.append(
                    {
                        "weight": float(c.weight),
                        "mean": sv(c),
                        "cov": [[float(x) for x in row] for row in c.covar.tolist()],
                    }
                )
            pre_reduce_snapshots = snap
        reduced_states = sort_components(reducer.reduce(updated_states))
        step_comps = []
        for reduced_state in reduced_states:
            tk = tag_key(reduced_state.tag)
            if tk not in ("birth", "null") and tk not in tag_map:
                tag_map[tk] = len(tag_map) + 2
            step_comps.append(
                {
                    "weight": float(reduced_state.weight),
                    "mean": sv(reduced_state),
                    "tag": tk if tk in ("birth", "null") else f"{tag_map[tk]:08x}",
                }
            )
        reduced_by_step.append(step_comps)

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "seed": SEED,
        "num_steps": number_steps,
        "prob_detection": probability_detection,
        "clutter_rate": clutter_rate,
        "death_probability": death_probability,
        "birth_probability": birth_probability,
        "clutter_spatial_density": clutter_spatial_density,
        "merge_threshold": merge_threshold,
        "prune_threshold": prune_threshold,
        "state_threshold": state_threshold,
        "missed_distance": 3.0,
        "init_cov_diag": [float(x) for x in np.diag(covar**2)],
        "init_weight": 0.25,
        "birth_cov_diag": [float(x) for x in np.diag(birth_covar**2)],
        "birth_weight": 0.25,
        "start_truths": [sv(t[0]) for t in initial_truths],
        # Preserve set insertion order — GM-PHD `order_by_detection` is order-sensitive.
        "measurements": [
            [[float(d.state_vector[0, 0]), float(d.state_vector[1, 0])] for d in ms]
            for ms in all_measurements
        ],
        "reduced_by_step": reduced_by_step,
        "pre_reduce_by_step": pre_reduce_by_step,
        "pre_reduce_snapshot_step1": pre_reduce_snapshots,
    }
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT, "and", RUST)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

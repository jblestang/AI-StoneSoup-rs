#!/usr/bin/env python3
"""Export Lot 18 — simple OOSM fixed-lag example fixtures."""
from __future__ import annotations

import hashlib
import json
from copy import deepcopy
from datetime import datetime, timedelta
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot18_simple_oosm.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot18_simple_oosm_fixtures.rs"


def state_mean(state) -> list[float]:
    return [float(state.state_vector[i, 0]) for i in range(4)]


def write_rust(payload: dict) -> None:
    n = payload["num_scans"]
    lines = [
        "// @generated by tools/python/export_lot18_simple_oosm.py — do not edit",
        f"pub const LOT18_NUM_SCANS: usize = {n};",
        f"pub const LOT18_Q: f64 = {payload['q']};",
        f"pub const LOT18_PRIOR_MEAN: [f64; 4] = {payload['prior_mean']};",
        f"pub const LOT18_PRIOR_COV_DIAG: [f64; 4] = {payload['prior_cov_diag']};",
        f"pub const LOT18_MEAS_NOISE_DIAG: [f64; 2] = {payload['meas_noise_diag']};",
        "pub const LOT18_TRUTH: [[f64; 4]; LOT18_NUM_SCANS] = [",
    ]
    for row in payload["truth"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT18_MEAS_XY: [[f64; 2]; LOT18_NUM_SCANS] = [")
    for row in payload["meas_xy"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT18_MEAS_TIME_SEC: [i64; LOT18_NUM_SCANS] = [")
    for t in payload["meas_time_sec"]:
        lines.append(f"    {t},")
    lines.append("];")
    lines.append("pub const LOT18_ARRIVAL_TRUTH_INDEX: [usize; LOT18_NUM_SCANS] = [")
    for i in payload["arrival_truth_index"]:
        lines.append(f"    {i},")
    lines.append("];")
    lines.append("pub const LOT18_NAIVE_TRACK: [[f64; 4]; LOT18_NUM_SCANS] = [")
    for row in payload["naive_track"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("pub const LOT18_OOSM_TRACK: [[f64; 4]; LOT18_NUM_SCANS] = [")
    for row in payload["oosm_track_at_arrival"]:
        lines.append(f"    {row},")
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    import numpy as np
    from stonesoup.models.measurement.linear import LinearGaussian
    from stonesoup.models.transition.linear import (
        CombinedLinearGaussianTransitionModel,
        ConstantVelocity,
    )
    from stonesoup.predictor.kalman import KalmanPredictor
    from stonesoup.types.detection import TrueDetection
    from stonesoup.types.groundtruth import GroundTruthPath, GroundTruthState
    from stonesoup.types.hypothesis import SingleHypothesis
    from stonesoup.types.state import GaussianState
    from stonesoup.types.track import Track
    from stonesoup.updater.kalman import KalmanUpdater

    start_time = datetime.now().replace(microsecond=0)
    np.random.seed(1908)
    num_steps = 65

    transition_model = CombinedLinearGaussianTransitionModel(
        [ConstantVelocity(0.05), ConstantVelocity(0.05)]
    )
    truth = GroundTruthPath(
        [GroundTruthState([0, 1, -100, 0.3], timestamp=start_time)]
    )
    timestamps = [start_time]
    for k in range(1, num_steps):
        truth.append(
            GroundTruthState(
                transition_model.function(
                    truth[k - 1],
                    noise=True,
                    time_interval=timedelta(seconds=2),
                ),
                timestamp=start_time + timedelta(seconds=5 * k),
            )
        )
        timestamps.append(truth[k].timestamp)

    measurement_model = LinearGaussian(
        ndim_state=4,
        mapping=(0, 2),
        noise_covar=np.diag([50.0, 50.0]),
    )
    scans = []
    meas_xy = []
    meas_time_sec = []
    truth_rows = []
    for k in range(num_steps):
        delay = 25 if k % 5 == 0 else 0
        measurement = measurement_model.function(truth[k], noise=True)
        meas_xy.append([float(measurement[0, 0]), float(measurement[1, 0])])
        meas_time_sec.append(int(5 * k))
        truth_rows.append(state_mean(truth[k]))
        detections = {
            TrueDetection(
                state_vector=measurement,
                groundtruth_path=truth,
                timestamp=truth[k].timestamp,
            )
        }
        scans.append(
            (truth[k].timestamp + timedelta(seconds=delay), k, detections)
        )

    arrival_time_ordered = sorted(scans, key=lambda dscan: dscan[0])
    arrival_truth_index = [row[1] for row in arrival_time_ordered]
    arrival_scans = [(row[0], row[2]) for row in arrival_time_ordered]

    predictor = KalmanPredictor(transition_model)
    updater = KalmanUpdater(measurement_model)
    prior = GaussianState(
        state_vector=[0, 1, -100, 0.3],
        covar=np.diag([1, 1, 1, 1]),
        timestamp=start_time,
    )
    prior_lag = deepcopy(prior)
    track_lag = Track(prior_lag)
    naive_track = []
    for _, scan in arrival_scans:
        for detection in scan:
            prediction = predictor.predict(prior_lag, timestamp=detection.timestamp)
            hypothesis = SingleHypothesis(prediction, detection)
            post = updater.update(hypothesis)
            track_lag.append(post)
            prior_lag = track_lag[-1]
            naive_track.append(state_mean(post))

    prior_oosm = deepcopy(prior)
    track = Track(prior_oosm)
    lag_storage = []
    oosm_track_at_arrival = []
    for k, (_arr, scan) in enumerate(arrival_scans):
        if k <= 4:
            lag_storage.append(scan)
        else:
            original_timestamps = []
            for stored in lag_storage:
                for detection in stored:
                    original_timestamps.append(detection.timestamp)
            index = np.argsort(original_timestamps)
            lag_storage = [lag_storage[i] for i in index]
            for detection in lag_storage[0]:
                prediction = predictor.predict(prior_oosm, timestamp=detection.timestamp)
                hypothesis = SingleHypothesis(prediction, detection)
                post = updater.update(hypothesis)
                track.append(post)
                prior_oosm = track[-1]
            lag_storage.pop(0)
            lag_storage.append(scan)
        if k >= len(arrival_scans) - 1:
            for kk in range(0, 4):
                for detection in lag_storage[kk]:
                    prediction = predictor.predict(prior_oosm, timestamp=detection.timestamp)
                    hypothesis = SingleHypothesis(prediction, detection)
                    post = updater.update(hypothesis)
                    track.append(post)
                    prior_oosm = track[-1]
        oosm_track_at_arrival.append(state_mean(prior_oosm))

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_scans": num_steps,
        "q": 0.05,
        "prior_mean": [0.0, 1.0, -100.0, 0.3],
        "prior_cov_diag": [1.0, 1.0, 1.0, 1.0],
        "meas_noise_diag": [50.0, 50.0],
        "truth": truth_rows,
        "meas_xy": meas_xy,
        "meas_time_sec": meas_time_sec,
        "arrival_truth_index": arrival_truth_index,
        "naive_track": naive_track,
        "oosm_track_at_arrival": oosm_track_at_arrival,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

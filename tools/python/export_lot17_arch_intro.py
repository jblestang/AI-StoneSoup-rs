#!/usr/bin/env python3
"""Export Lot 17 — Introduction to Architectures (static topology fixture)."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

UPSTREAM_SHA = "a4336b920a799cfe0a77ecb05867c5deeb371c7a"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "verification" / "fixtures" / "lot17_arch_intro.json"
RUST = ROOT / "crates" / "stonesoup-scenarios" / "src" / "lot17_arch_intro_fixtures.rs"

# Viewer layout: fusion node A above children B and C (matches tutorial edge direction).
VIEWER_LAYOUT = {
    "Node A": [0.0, 40.0],
    "Node B": [-35.0, 0.0],
    "Node C": [35.0, 0.0],
}


def write_rust(payload: dict) -> None:
    lines = [
        "// @generated by tools/python/export_lot17_arch_intro.py — do not edit",
        f"pub const LOT17_NUM_NODES: usize = {payload['num_nodes']};",
        f"pub const LOT17_NUM_EDGES: usize = {payload['num_edges']};",
        f"pub const LOT17_NODE_A: [f64; 2] = {payload['node_a_xy']};",
        f"pub const LOT17_NODE_B: [f64; 2] = {payload['node_b_xy']};",
        f"pub const LOT17_NODE_C: [f64; 2] = {payload['node_c_xy']};",
        "pub const LOT17_EDGES: [(&str, &str); LOT17_NUM_EDGES] = [",
    ]
    for child, parent in payload["edges"]:
        lines.append(f'    ("{child}", "{parent}"),')
    lines.append("];")
    lines.append("")
    RUST.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    from stonesoup.architecture import InformationArchitecture
    from stonesoup.architecture.edge import Edge, Edges
    from stonesoup.architecture.node import Node

    node_a = Node(label="Node A")
    node_b = Node(label="Node B")
    node_c = Node(label="Node C")
    node_a.colour = "#006494"
    node_a.shape = "hexagon"

    edges = Edges(
        edges=[
            Edge(nodes=(node_b, node_a)),
            Edge(nodes=(node_c, node_a)),
        ]
    )
    arch = InformationArchitecture(edges=edges)
    if len(arch.all_nodes) != 3:
        raise SystemExit(f"expected 3 nodes, got {len(arch.all_nodes)}")
    if len(arch.edges) != 2:
        raise SystemExit(f"expected 2 edges, got {len(arch.edges)}")

    edge_rows = []
    for edge in arch.edges:
        child, parent = edge.nodes
        edge_rows.append([child.label, parent.label])

    payload = {
        "upstream_sha": UPSTREAM_SHA,
        "num_nodes": 3,
        "num_edges": 2,
        "node_a_xy": VIEWER_LAYOUT["Node A"],
        "node_b_xy": VIEWER_LAYOUT["Node B"],
        "node_c_xy": VIEWER_LAYOUT["Node C"],
        "edges": edge_rows,
    }
    text = json.dumps(payload, indent=2, sort_keys=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text + "\n", encoding="utf-8")
    write_rust(payload)
    print("wrote", OUT)
    print("wrote", RUST)
    print("sha256", hashlib.sha256(text.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
